import assert from 'node:assert/strict';
import { P36AutonomousSelfDevelopmentEngine } from '../src/organism/learning/P36AutonomousSelfDevelopment.ts';
const e=new P36AutonomousSelfDevelopmentEngine();
const state={tick:11,predictionError:.70,selfPredictionError:.34,autonomyScore:.61,attentionBudget:.76,needs:{energy:.83,cognitiveLoad:.20,uncertainty:.68,socialNeed:.24,novelty:.46,identityCoherence:.80,goalPressure:.44}};
const decision=e.selectDevelopmentFocus(state,{worldError01:.73,selfError01:.39,resourceRisk01:.15});
assert.ok(decision.score01>0.36);
const h=e.propose(state,{worldError01:.73,selfError01:.39,resourceRisk01:.15});
assert.ok(h);
const cycle=e.beginAutonomousDevelopmentCycle({hypothesisId:h.id,origin:'autonomous-gap'});
assert.ok(cycle);
const plan=e.developmentCampaignPlan();
assert.ok(plan.length>0 && plan.length<=96);
assert.equal(plan.filter(x=>x.holdout).length,cycle.requiredHoldout);
assert.ok(plan.every(x=>x.hypothesisId===h.id&&x.cycleId===cycle.id));
assert.ok(plan.some(x=>x.phase==='baseline')&&plan.some(x=>x.phase==='delayed-test')&&plan.some(x=>x.phase==='holdout'));
const agenda=e.learningAgenda();
assert.equal(agenda.selectedHypothesisId,h.id);
assert.ok(/^d-voi:/.test(agenda.reason));
console.log('SELF_DIRECTED_LEARNING_AUDIT=PASS',JSON.stringify({area:decision.area,score01:Number(decision.score01.toFixed(3)),slots:plan.length,holdout:cycle.requiredHoldout}));
