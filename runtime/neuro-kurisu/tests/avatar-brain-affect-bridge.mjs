import assert from 'node:assert/strict';
import { projectAvatarBrainState } from '../src/organism/body/AvatarBrainAffectBridge.ts';
import { EmbodimentRuntime } from '../src/organism/body/EmbodimentRuntime.ts';
const state={needs:{energy:.8,cognitiveLoad:.2,uncertainty:.2,socialNeed:.7,novelty:.8,identityCoherence:.8,goalPressure:.3},predictionError:.1,lastActionSuccess:.9,lastPredictionConfidence:.85,autonomyScore:.75};
const body={awake:true,bodyEnergy01:.82,thermalStrain01:.1,cognitiveCapacity01:.9};
const two=projectAvatarBrainState({state,body,now:10000,profile:'2d'});
const personality={adaptiveNames:['warmth','curiosity','playfulness','composure','directness'],adaptiveValues:[.95,.9,.85,.8,.7]};
const personaProjection=projectAvatarBrainState({state,body,personality,now:10000,profile:'2d'});
assert.ok(personaProjection.affect.warmth01>two.affect.warmth01,'P2702 personality traits modulate avatar warmth');
assert.ok(personaProjection.channels.mouthSmile>=two.channels.mouthSmile,'playfulness affects expression rendering');
assert.equal(two.profile,'2d');assert.equal(two.schemaVersion,1);
for(const v of Object.values(two.channels))assert.ok(Number.isFinite(v));
assert.ok(two.channels.eyeOpen>=0&&two.channels.eyeOpen<=1);
const layered=projectAvatarBrainState({state,body,now:10000,profile:'2.5d'});
assert.ok(Number.isFinite(layered.rendererHints.layered2d.faceRig01));
const spatial=projectAvatarBrainState({state,body,now:10000,profile:'3d'});
assert.ok(Number.isFinite(spatial.rendererHints.spatial3d.headPitch));
const stress=projectAvatarBrainState({state:{...state,needs:{...state.needs,cognitiveLoad:.98,uncertainty:.95},predictionError:.99},body:{...body,thermalStrain01:.95},now:20000});
assert.ok(stress.affect.stress01>two.affect.stress01);assert.equal(stress.reducedMotion,true);
const asleep=projectAvatarBrainState({state,body:{...body,awake:false},now:30000});
assert.equal(asleep.channels.idleMotion,0);assert.equal(asleep.channels.lipSyncGain,0);
const clamped=projectAvatarBrainState({state:{...state,needs:{...state.needs,energy:NaN,cognitiveLoad:99,novelty:-20},predictionError:Infinity},affect:{valence01:999,arousal01:-10,sampledAt:40000},now:40000});
for(const v of Object.values(clamped.affect))assert.ok(Number.isFinite(v)&&v>=0&&v<=1);
assert.ok(clamped.affect.valence01>=0&&clamped.affect.valence01<=1,'valence remains normalized');
const negativeValence=projectAvatarBrainState({state,affect:{valence01:-100},now:41000});assert.equal(negativeValence.affect.valence01,0);
const next=projectAvatarBrainState({state:{...state,needs:{...state.needs,cognitiveLoad:.95,uncertainty:.9}},body,previous:two,now:10100});
assert.ok(Math.abs(next.affect.stress01-two.affect.stress01)<.5);
const repeated=projectAvatarBrainState({state,body,now:10000});assert.deepEqual(repeated.channels,two.channels);
const stale=projectAvatarBrainState({state,affect:{valence01:1,arousal01:1,sampledAt:1},now:60000});
assert.ok(stale.freshness01<.01);
console.log('avatar-brain-affect-bridge: PASS');

const runtime=new EmbodimentRuntime();
const integrated=runtime.avatarProjection(state,{profile:'2d',personality,now:70000});
assert.equal(integrated.source,'organism-state');
assert.equal(integrated.profile,'2d');
const integratedNext=runtime.avatarProjection({...state,needs:{...state.needs,cognitiveLoad:.9}},{profile:'2.5d',now:70100});
assert.equal(integratedNext.profile,'2.5d');
assert.ok(Math.abs(integratedNext.affect.stress01-integrated.affect.stress01)<.5,'EmbodimentRuntime retains smoothing state across frames');
