import { B299CausalPersonalityDevelopmentLoop } from '../src/organism/system/B299CausalPersonalityDevelopmentLoop.ts';
const A=['respond','explore','verify','rest','reflect','wait','defer'];
const assert=(x,m)=>{if(!x)throw new Error(m)};
const l1=(a,b)=>A.reduce((s,k)=>s+Math.abs((a[k]??0)-(b[k]??0)),0);
const loop=new B299CausalPersonalityDevelopmentLoop();
loop.setContext({social:1,epistemic:0,autonomy:0,maintenance:0});
for(let i=0;i<40;i++) loop.observeOutcome({tick:i,action:'respond',reward01:.9,predictionError01:.12,causalConfidence01:.86,identityContinuity01:.9,externalEvidence01:1,worldTransition:true,independent:true,autonomous:false,predictedUtility01:.8,neuralPlasticity01:.8,context:{social:1,epistemic:0,autonomy:0,maintenance:0}});
const social=loop.actionBias('respond');
loop.setContext({social:0,epistemic:1,autonomy:0,maintenance:0});
const epistemicBefore=loop.actionBias('respond');
for(let i=0;i<40;i++) loop.observeOutcome({tick:40+i,action:'respond',reward01:.2,predictionError01:.55,causalConfidence01:.72,identityContinuity01:.9,externalEvidence01:1,worldTransition:true,independent:true,autonomous:false,predictedUtility01:.6,neuralPlasticity01:.7,context:{social:0,epistemic:1,autonomy:0,maintenance:0}});
const epistemicAfter=loop.actionBias('respond');
loop.setContext({social:1,epistemic:0,autonomy:0,maintenance:0});
const socialAfter=loop.actionBias('respond');
const d=loop.diagnostics();
assert(d.contextCreditAssignments===80,'B300 context credit count mismatch');
assert(social>0.005,'positive social learning did not alter response preference');
assert(epistemicAfter<epistemicBefore,'negative epistemic outcomes did not lower epistemic response preference');
assert(socialAfter>epistemicAfter,'contextual personality collapsed into one global preference');
assert(d.contextDiagnostics.find(x=>x.action==='respond').contextEvidence01.social>0,'social evidence was not recorded');
assert(d.contextDiagnostics.find(x=>x.action==='respond').contextEvidence01.epistemic>0,'epistemic evidence was not recorded');
loop.lesion(.95);
assert(Math.abs(loop.actionBias('respond'))<Math.abs(socialAfter)*.2+1e-9,'lesion failed to suppress contextual personality influence');
console.log(JSON.stringify({pass:true,contextCreditAssignments:d.contextCreditAssignments,social,socialAfter,epistemicBefore,epistemicAfter,context:d.contextDiagnostics.find(x=>x.action==='respond')}));
