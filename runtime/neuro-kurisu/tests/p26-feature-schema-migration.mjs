import assert from 'node:assert/strict';
import { ParametricPolicyLearner, defaultParametricPolicy } from '../src/organism/learning/ParametricPolicyLearner.ts';

const oldNames=['energy','cognitiveLoad','uncertainty','novelty','goalPressure','socialNeed','predictionError','attentionBudget','identityCoherence','externalInput','bodyCapacity','thermalPressure','boredom','resourceRisk','actionCost'];
const legacy=defaultParametricPolicy();
legacy.featureNames=[...oldNames];
for(const action of ['respond','explore','verify','rest','reflect','wait','defer'])legacy.weights[action]=new Array(15).fill(0);
legacy.weights.respond[0]=.25;
legacy.weights.respond[14]=1.5;
const learner=new ParametricPolicyLearner();
learner.restore(legacy);
const migrated=learner.snapshot();
assert.equal(migrated.featureNames.length,21);
assert.equal(migrated.weights.respond.length,21);
assert.equal(migrated.weights.respond[0],.25,'existing feature weight must be preserved');
assert.equal(migrated.weights.respond[14],0,'new interaction feature must initialize without stealing old action-cost weight');
assert.equal(migrated.weights.respond[17],1.5,'legacy action-cost weight must migrate by feature name');
assert.equal(migrated.featureNames[17],'actionCost');
assert.deepEqual(migrated.weights.respond.slice(18),[0,0,0],'new context interaction weights must initialize at zero');
assert.deepEqual(migrated.featureNames.slice(18),['energyBelowHalf','noveltyBelowHalf','energyNoveltyClassInteraction']);
const state=(energy,novelty)=>({needs:{energy,novelty,cognitiveLoad:.2,uncertainty:.2,goalPressure:.2,socialNeed:.2,identityCoherence:.8},predictionError:.1,attentionBudget:.8});
const lowNoveltyContext=learner.features(state(.25,.2),undefined,'rest');
const highNoveltyContext=learner.features(state(.25,.8),undefined,'rest');
assert.equal(lowNoveltyContext[18],1,'low energy must activate the energy hinge');
assert.equal(lowNoveltyContext[19],1,'low novelty must activate the novelty hinge');
assert.equal(lowNoveltyContext[20],1,'joint low-energy/low-novelty context must activate the interaction');
assert.equal(highNoveltyContext[18],1);
assert.equal(highNoveltyContext[19],0);
assert.equal(highNoveltyContext[20],0,'distinct novelty regimes must map to distinct interaction values');
console.log('P26_FEATURE_SCHEMA_MIGRATION=PASS',{oldFeatures:15,newFeatures:21,actionCostPreserved:true,newInteractionsZeroInitialized:true,contextInteractions:true});
