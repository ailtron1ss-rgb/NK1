import assert from 'node:assert/strict';
import { OrganismRuntime } from '../src/organism/core/OrganismRuntime.ts';
import { MemoryStateStore } from '../src/organism/persistence/MemoryStateStore.ts';
import { BoundedOperationalJournal } from '../src/organism/persistence/BoundedOperationalJournal.ts';
const store=new MemoryStateStore();
const runtime=new OrganismRuntime({stateFile:'b301-economy.json',worldStateFile:'b301-world.json',enableLanguage:false,performanceProfile:'mobile',stateStore:store,worldStateStore:store,journal:new BoundedOperationalJournal(),checkpointMaxDirtyCycles:256,checkpointMinIntervalMs:600000});
await runtime.init();
for(let i=0;i<24;i++) await runtime.step(i%4===0?'Investigate an uncertain claim and verify the consequences.':undefined);
await runtime.core.flush();
const persisted=await store.load();
const snap=runtime.core.snapshot();
const econ=runtime.core.mobileStateEconomyDiagnostics();
const b296=runtime.core.b296NeuralPersonalityAgencyDiagnostics();
const b299=persisted.system.causalPersonalityDevelopmentB299;
assert.ok(b296.cycles>0,'B296 did not execute');
assert.ok(b296.learningUpdates>0,'B296 did not learn');
assert.ok(b296.synapticUpdates>0,'B296 synapses did not change');
assert.ok(b299?.learningUpdates===24,'B299 learning count mismatch');
assert.ok(persisted.system.mobileStateEconomyB301,'B301 state missing');
assert.ok(Array.isArray(persisted.system.mobileStateEconomyB301.protectedCanonicalBranches),'B301 canonical protection metadata missing');
assert.ok((persisted.traces?.length??0)<=16,'trace compaction limit failed');
assert.ok((persisted.facets.memory.eventLog?.length??0)<=96,'event compaction limit failed');
const restoredNucleus=await import('../src/organism/system/B296NeuralPersonalityAgencyNucleus.ts').then(({B296NeuralPersonalityAgencyNucleus})=>{const n=new B296NeuralPersonalityAgencyNucleus();n.restore(persisted.system.neuralPersonalityAgencyNucleusB296);return n});
assert.ok(restoredNucleus.diagnostics().learningUpdates>=b296.learningUpdates,'B296 restore failed');
const restarted=new OrganismRuntime({stateFile:'b301-economy.json',worldStateFile:'b301-world.json',enableLanguage:false,performanceProfile:'mobile',stateStore:store,worldStateStore:store,journal:new BoundedOperationalJournal(),checkpointMaxDirtyCycles:256,checkpointMinIntervalMs:600000});
await restarted.init();
const restartedPersisted=await store.load();
assert.equal(restartedPersisted.state.tick,persisted.state.tick,'full organism restart tick mismatch');
assert.equal(restartedPersisted.system.causalPersonalityDevelopmentB299.learningUpdates,24,'B299 was not durable across full restart');
assert.equal(restartedPersisted.system.neuralPersonalityAgencyNucleusB296.learningUpdates,b296.learningUpdates,'B296 was not durable across full restart');
assert.ok(restartedPersisted.system.mobileStateEconomyB301,'B301 economy state missing after full restart');
restarted.stop();
await runtime.stop();
console.log(JSON.stringify({pass:true,tick:snap.state.tick,economy:econ,b296:{cycles:b296.cycles,learningUpdates:b296.learningUpdates,learningEligibleCycles:b296.learningEligibleCycles,synapticUpdates:b296.synapticUpdates},b299LearningUpdates:b299.learningUpdates,payloadBytes:econ.lastBytesAfter,traces:persisted.traces.length,eventLog:persisted.facets.memory.eventLog.length,restoreB296LearningUpdates:restoredNucleus.diagnostics().learningUpdates,fullRestart:true}));
// Standalone runtime smoke completed all durability assertions; terminate the harness explicitly.
process.exit(0);
