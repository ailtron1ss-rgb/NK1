import assert from 'node:assert/strict';
import { RevisionGraph } from '../src/organism/persistence/RevisionGraph.ts';
import { RevisionTokenRegistry } from '../src/organism/persistence/RevisionTokenRegistry.ts';
const graph=new RevisionGraph();
const reg=new RevisionTokenRegistry(graph);
const before=reg.token('memory-core');
assert.equal(before.revision,0);
reg.touch('memory-core',1,'encode');
reg.touch('memory-fabric',1,'recall');
const a=reg.token('memory-core');
const b=reg.token('memory-fabric');
assert.equal(a.revision,1);
assert.equal(b.revision,1);
assert.equal(graph.currentSnapshot().current.memory,2);
assert.equal(a.materializedRevision,0);
assert.equal(b.materializedRevision,0);
assert.equal(a.domain,'memory');
assert.equal(a.dirty,true);
const all=reg.all();
assert.equal(all.length,8);
assert.ok(all.some(x=>x.subsystem==='reality-model'&&x.domain==='reality'));
console.log(`REVISION_TOKEN_REGISTRY=PASS subsystems=${all.length} memoryRevision=${a.revision}`);
