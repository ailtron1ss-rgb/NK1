import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {FileStateStore} from '../src/organism/persistence/FileStateStore.ts';
import {OrganismCore} from '../src/organism/core/OrganismCore.ts';
const dir=await mkdtemp(join(tmpdir(),'nk169-')); const file=join(dir,'state.json');
const store=new FileStateStore(file); const core=new OrganismCore(store,{enableSelfPrediction:true,enableWorldModel:true}); await core.init();
await core.observe({text:'investigate unfamiliar signal and verify the result',surprise:.72,worldContext:{location:'lab',facts:['signal-changing'],objects:[{id:'s',label:'signal',location:'lab',value:.8,visible:true,collected:false}],events:['signal']} ,embodiment:{bodyEnergy01:.8,cognitiveCapacity01:.82,thermalStrain01:.15,sensoryFreshness01:.95,awake:true,battery01:.85,cpuLoad01:.18,ramPressure01:.22}});
const ap=core.activePerceptionSnapshot(); assert(ap.proposed>=1); assert(ap.lastRequest?.status==='proposed');
assert.equal(core.activePerceptionComplete(ap.lastRequest.id,0.74),true);
assert(core.activePerceptionSnapshot().executed>=1);
await core.feedback({success:.85,reward:.8,surprise:.18,evidenceSource:'oracle'});
const wc=core.worldCausalCalibrationSnapshot(); assert(wc.resolved>=1);
const sm=core.selfModelValidationSnapshot(); assert(sm.predictions>=1);
const fg=core.failureRecoveryCertificationSnapshot(); assert(fg.checkpoints>=1);
await core.endTemporalSession('big-pass-169-test',true);
const core2=new OrganismCore(new FileStateStore(file),{enableSelfPrediction:true,enableWorldModel:true}); await core2.init();
assert(core2.worldCausalCalibrationSnapshot().resolved>=1); assert(core2.selfModelValidationSnapshot().predictions>=1); assert(core2.failureRecoveryCertificationSnapshot().checkpoints>=1);
await core2.endTemporalSession('big-pass-169-restart',true); await rm(dir,{recursive:true,force:true});
console.log(JSON.stringify({ok:true,activePerception:ap.proposed,worldCalibration:wc.resolved,selfValidation:sm.resolved,recovery:fg.checkpoints,restart:true}));
