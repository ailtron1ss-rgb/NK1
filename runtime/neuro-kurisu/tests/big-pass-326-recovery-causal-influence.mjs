import assert from 'node:assert/strict';
import { rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { OrganismRuntime } from '../src/organism/core/OrganismRuntime.ts';

const base=path.join(tmpdir(),`nk326-recovery-causal-${process.pid}-${Date.now()}`);
const opts={stateFile:base+'.json',worldStateFile:base+'.world.json',autoRun:false,enableLanguage:false,intervalMs:5000,checkpointMinIntervalMs:0,checkpointMaxDirtyCycles:1};
const input={embodiment:{bodyEnergy01:.82,cognitiveCapacity01:.80,thermalStrain01:.22,sensoryFreshness01:.82,battery01:.80,cpuLoad01:.28,ramPressure01:.25,awake:true},novelty:.45,surprise:.16,text:'Same post-recovery decision context.'};
const first=new OrganismRuntime(opts); await first.init(); await first.flush();
const before=first.core.recoveryPolicyDiagnostics();
first.stop();
const second=new OrganismRuntime(opts); await second.init();
const recovered=second.core.recoveryPolicyDiagnostics();
assert(recovered.recovery.continuityShock01>0.5);
assert(recovered.recovery.postRecoveryIntegration01>0);
assert(recovered.biases.explore<0);
assert(recovered.biases.verify>0);
assert(recovered.biases.rest>0);
const recoveredCycle=await second.core.observeOperational(input);
const healedBefore=recoveredCycle.state;
for(let i=0;i<12;i++) await second.core.observeOperational({...input,text:undefined,surprise:.05,novelty:.30});
const healed=second.core.recoveryPolicyDiagnostics();
assert(healed.recovery.continuityShock01 < recovered.recovery.continuityShock01);
assert(healed.recovery.postRecoveryIntegration01 > recovered.recovery.postRecoveryIntegration01);
assert(Math.abs(healed.biases.explore) < Math.abs(recovered.biases.explore));
assert(healed.biases.verify < recovered.biases.verify);
const selectedBefore=recoveredCycle.decision.selected?.action ?? 'wait';
const selectedAfter=((await second.core.observeOperational({...input,text:undefined,surprise:.05,novelty:.30})).decision.selected?.action ?? 'wait');
assert.equal(typeof selectedBefore,'string'); assert.equal(typeof selectedAfter,'string');
second.stop();
for(const suffix of ['.json','.world.json','.continuity.jsonl','.operational.jsonl','.json.bak','.world.json.bak','.world.json.tmp']) await rm(base+suffix,{force:true});
console.log(JSON.stringify({pass:true,before,recovered,healed,selectedBefore,selectedAfter},null,2));
