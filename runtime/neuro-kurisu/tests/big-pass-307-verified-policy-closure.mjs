import assert from 'node:assert/strict';
import { AdaptivePolicyEngine } from '../src/organism/learning/AdaptivePolicyEngine.ts';
import { OrganismCore } from '../src/organism/core/OrganismCore.ts';
import { MemoryStateStore } from '../src/organism/persistence/MemoryStateStore.ts';

const context='e2|c1|u2|n2|g1|s1';
const engine=new AdaptivePolicyEngine();
const baseline=engine.bias(context,'verify',.5);
for(let i=0;i<12;i++) engine.update(context,'verify',.5,context);
const preClosure=engine.bias(context,'verify',.5);
for(let i=0;i<12;i++) engine.observeVerifiedOutcome(context,'verify',.92,.82,true,true);
const postClosure=engine.bias(context,'verify',.5);
const row=engine.snapshot().values[context].verify;
assert.ok(postClosure>preClosure+.001,'verified closure did not change policy bias');
assert.equal(row.verifiedUpdates,12,'verified updates count incorrect');
assert.ok(row.verifiedValue>.52,'verified value did not move toward verified reward');
assert.ok(Math.abs(engine.verifiedClosure(context,'verify',.5))>.001,'verified closure signal too small');
const negativeEngine=new AdaptivePolicyEngine();
for(let i=0;i<12;i++) negativeEngine.observeVerifiedOutcome(context,'verify',.08,.86,true,true);
const negativeBias=negativeEngine.bias(context,'verify',.5);
assert.ok(negativeBias<-.001,'negative verified outcome did not suppress policy bias');
const restoredEngine=new AdaptivePolicyEngine();
restoredEngine.restore(engine.snapshot());
assert.equal(restoredEngine.snapshot().values[context].verify.verifiedUpdates,12,'verified branch lost in policy restore');
assert.ok(restoredEngine.bias(context,'verify',.5)>preClosure+.001,'restored policy lost verified influence');
const legacyEngine=new AdaptivePolicyEngine();
legacyEngine.restore({version:1,values:{legacy:{verify:{value:.72,updates:4,rewardMean:.7,rewardVariance:.08,confidence01:.55,lastUpdatedAt:1}}},updates:4,rewardedUpdates:3,penalizedUpdates:1,explorationRate01:.18,lastContextKey:'legacy',lastAction:'verify',lastUpdateAt:1});
const legacyRow=legacyEngine.snapshot().values.legacy.verify;
assert.equal(legacyRow.verifiedUpdates,0,'legacy row should start without verified updates');
assert.ok(Math.abs(legacyRow.verifiedValue-.72)<1e-9,'legacy value was not migrated into verified baseline');

const core=new OrganismCore(new MemoryStateStore(),{performanceProfile:'mobile',cycleResultMode:'operational',enableTemporalResolutionGovernor:true,operationalPulseEvery:4,checkpointMaxDirtyCycles:256,checkpointMinIntervalMs:600000});
await core.init();
let full=0, verified=0;
for(let i=0;i<32;i++){
  const embodiment={bodyEnergy01:.86-i*.003,cognitiveCapacity01:.86,thermalStrain01:i>26?.68:.16,sensoryFreshness01:.84,battery01:.82-i*.004,cpuLoad01:i>26?.72:.20,ramPressure01:i>26?.70:.16,awake:true};
  const result=await core.observeOperational(i%2===0?{text:'Verify the consequence before committing.',novelty:.28,surprise:.10,embodiment}:{embodiment});
  const isFull=result.workspace.content.temporalResolution!=='micro';
  if(!isFull) continue;
  full++;
  const action=result.decision?.selected?.action??'verify';
  const reward=action==='verify'?.88:action==='explore'?.76:action==='reflect'?.72:action==='rest'?.70:.62;
  const world=i%2===0?{action,before:{tick:i,location:'verified-policy',energy:.82,attention:.73,uncertainty:.55,facts:[`before-${i}`],objects:[],events:[`before-${i}`]},after:{tick:i+1,location:'verified-policy',energy:.77,attention:.80,uncertainty:.28,facts:[`before-${i}`,`after-${i}`],objects:[],events:[`before-${i}`,`after-${i}`]},reward,surprise:.10,at:Date.now()}:undefined;
  if(world) verified++;
  await core.feedback({success:reward,reward,surprise:.10,evidenceSource:world?'external':'unknown',worldTransition:world});
}
const persisted=core.snapshot().facets.learning.adaptivePolicy;
const rows=Object.values(persisted.values ?? {}).flatMap(v=>Object.entries(v ?? {}).map(([action,row])=>({action,row})));
const verifiedRows=rows.filter(x=>Number(x.row?.verifiedUpdates??0)>0);
const maxVerifiedUpdates=Math.max(0,...verifiedRows.map(x=>Number(x.row?.verifiedUpdates??0)));
const maxVerifiedValue=Math.max(0,...verifiedRows.map(x=>Number(x.row?.verifiedValue??.5)));
assert.ok(full>=12,'B307 core integration did not produce enough full cycles');
assert.ok(verified>=6,'B307 did not exercise enough verified outcomes');
assert.ok(verifiedRows.length>0,'B307 core did not persist verified policy rows');
assert.ok(maxVerifiedUpdates>0,'B307 verified update count did not persist');
assert.ok(maxVerifiedValue>.51,'B307 verified policy value did not move');
const restored=new OrganismCore(new MemoryStateStore({initial:core.snapshot()}),{performanceProfile:'mobile',cycleResultMode:'operational',enableTemporalResolutionGovernor:true,operationalPulseEvery:4,checkpointMaxDirtyCycles:256,checkpointMinIntervalMs:600000});
await restored.init();
const restoredRows=Object.values(restored.snapshot().facets.learning.adaptivePolicy.values ?? {}).flatMap(v=>Object.entries(v ?? {}).map(([action,row])=>({action,row})));
const restoredVerifiedUpdates=Math.max(0,...restoredRows.map(x=>Number(x.row?.verifiedUpdates??0)));
assert.equal(restoredVerifiedUpdates,maxVerifiedUpdates,'B307 verified policy evidence lost after restart');
console.log(JSON.stringify({pass:true,unit:{baseline,preClosure,postClosure,verifiedUpdates:row.verifiedUpdates,verifiedValue:row.verifiedValue,verifiedClosure:engine.verifiedClosure(context,'verify',.5)},core:{full,verified,verifiedRows:verifiedRows.length,maxVerifiedUpdates,maxVerifiedValue},restart:true},null,2));
process.exit(0);
