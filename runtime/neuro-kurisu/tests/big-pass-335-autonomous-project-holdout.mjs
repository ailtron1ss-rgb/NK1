import assert from 'node:assert/strict';
import { B335AutonomousProjectHoldoutGate } from '../src/organism/system/B335AutonomousProjectHoldoutGate.ts';
const g=new B335AutonomousProjectHoldoutGate();
g.setPhase('baseline');
for(const a of ['explore','explore','verify','wait','explore']) g.observe({projectId:null,projectActive:false,contextKey:'base',selectedAction:a,outcome01:.5,verifiedOutcome:true});
g.setPhase('training');
for(let i=0;i<4;i++) g.observe({projectId:'p1',projectActive:true,contextKey:'train',selectedAction:'explore',outcome01:.8,verifiedOutcome:true});
g.setPhase('holdout');
for(const a of ['verify','verify','rest','verify']) g.observe({projectId:'p1',projectActive:true,contextKey:'holdout',selectedAction:a,outcome01:.72,verifiedOutcome:true});
let d=g.diagnostics();
assert.equal(d.evaluation.eligible,true); assert.equal(d.projectId,'p1'); assert.equal(d.strategyRetention01,1);
const s=g.snapshot(); const r=new B335AutonomousProjectHoldoutGate(); r.restore(s); assert.deepEqual(r.snapshot(),s);
const bad=new B335AutonomousProjectHoldoutGate(); bad.setPhase('baseline');
for(let i=0;i<4;i++) bad.observe({projectId:null,projectActive:false,contextKey:'base',selectedAction:'wait',outcome01:.5,verifiedOutcome:true});
bad.setPhase('training'); for(let i=0;i<3;i++) bad.observe({projectId:'p2',projectActive:true,contextKey:'train',selectedAction:'wait',outcome01:.8,verifiedOutcome:true});
bad.setPhase('holdout'); for(let i=0;i<4;i++) bad.observe({projectId:'p2',projectActive:true,contextKey:'holdout',selectedAction:'wait',outcome01:.8,verifiedOutcome:true});
assert.equal(bad.diagnostics().evaluation.eligible,false);
console.log(JSON.stringify({pass:true,good:d.evaluation,bad:bad.diagnostics().evaluation,persistence:true},null,2));
