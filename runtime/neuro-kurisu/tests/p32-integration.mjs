import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { FileStateStore } from '../src/organism/persistence/FileStateStore.ts';
import { OrganismRuntime } from '../src/organism/core/OrganismRuntime.ts';
const dir=await mkdtemp(join(tmpdir(),'neuro-p32-')); const store=new FileStateStore(join(dir,'state.json'),{backupEverySaves:2});
const runtime=new OrganismRuntime({stateFile:join(dir,'state.json'),intervalMs:5000,checkpointMinIntervalMs:0,checkpointMaxDirtyCycles:1,enableLanguage:false,autoRun:false});
await runtime.init();
const r=await runtime.step('explore a little',{deliberate:false});
assert.ok(r.cycle.decision.selected);
const snap=runtime.core.p32Snapshot();
assert.ok(snap.nodes.length > 0);
assert.equal(snap.pendingPrediction, null);
await runtime.core.flush();
const raw=await store.load(); assert.ok(raw?.facets?.consciousness?.p32);
const runtime2=new OrganismRuntime({stateFile:join(dir,'state.json'),intervalMs:5000,enableLanguage:false,autoRun:false}); await runtime2.init();
assert.deepEqual(runtime2.core.p32Snapshot(),raw.facets.consciousness.p32);
console.log('P32_INTEGRATION=PASS');
console.log(JSON.stringify({tick:runtime2.core.snapshot().state.tick,p32Nodes:runtime2.core.p32Diagnostics().nodes,p32Edges:runtime2.core.p32Diagnostics().edges}));
