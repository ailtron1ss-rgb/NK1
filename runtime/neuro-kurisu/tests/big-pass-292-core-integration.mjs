import assert from 'node:assert/strict';
import { OrganismRuntime } from '../src/organism/core/OrganismRuntime.ts';
import { MemoryStateStore } from '../src/organism/persistence/MemoryStateStore.ts';
import { BoundedOperationalJournal } from '../src/organism/persistence/BoundedOperationalJournal.ts';
const r=new OrganismRuntime({stateFile:'b292-test.json',worldStateFile:'b292-world.json',enableLanguage:false,stateStore:new MemoryStateStore(),worldStateStore:new MemoryStateStore(),journal:new BoundedOperationalJournal()});
await r.init();
for(let i=0;i<24;i++) await r.step(i%6===0?'Independently investigate a claim, preserve the goal, and adapt after the outcome.':undefined);
const bus=r.core.b292CognitiveStateBusDiagnostics();
const trace=r.core.b292IntentTraceDiagnostics();
const b291=r.core.b291UnifiedSelfAgencyDiagnostics();
const b290=r.core.b290RealityGatedNeurodevelopmentDiagnostics();
assert.equal(bus.version,1,'B292 state bus schema');
assert.ok(Number.isFinite(bus.readiness01),'B292 readiness finite');
assert.ok(trace.records.length>0,'B292 intent trace has decision evidence');
assert.ok(trace.outcomeCount>=0,'B292 outcome counter valid');
assert.ok(Number.isFinite(trace.commitment01),'B292 commitment finite');
assert.ok(Number.isFinite(b291.gate01),'B291 remains live');
assert.ok(Number.isFinite(b290.realityGate01),'B290 remains live');
const snap=r.core.snapshot();
assert.ok(snap.system.cognitiveStateBusB292,'B292 bus persisted');
assert.ok(snap.system.intentTraceB292,'B292 trace persisted');
console.log(JSON.stringify({pass:true,tick:snap.state.tick,b292:{readiness01:bus.readiness01,stability01:bus.stability01,commitment01:trace.commitment01,continuity01:trace.continuity01,records:trace.records.length},b291:{mode:b291.mode,gate01:b291.gate01},b290:{mode:b290.mode,realityGate01:b290.realityGate01}}));
await r.stop();
