import assert from 'node:assert/strict';
import { FutureSimulator } from '../src/organism/developmental/FutureSimulator.ts';
const simulator=new FutureSimulator();
assert.equal('worldForge' in simulator,false,'runtime callers must not receive the evaluator engine object');
assert.deepEqual(simulator.generateWorldForgeScenarios({split:'holdout',seed:77,count:3}),[],'agent-facing simulator API must not generate holdout cases');
let splitGetterInvoked=false;
const hostileRequest={seed:7};
Object.defineProperty(hostileRequest,'split',{enumerable:true,get(){splitGetterInvoked=true;return 'train';}});
assert.deepEqual(simulator.generateWorldForgeScenarios(hostileRequest),[]);
assert.equal(splitGetterInvoked,false,'runtime facade must not invoke generation request getters');
const scenarios=simulator.generateWorldForgeScenarios({split:'train',seed:77,count:3});
assert.equal(scenarios.length,3);
const initial=simulator.startWorldForgeScenario(scenarios[0]);
assert.ok(initial);
const transition=simulator.stepWorldForgeScenario(initial,{action:'observe'});
assert.equal(transition.accepted,true);
assert.equal(transition.state.tick,1);
assert.equal(typeof simulator.evaluateWorldForgeScenario,'undefined','runtime API must not accept caller-forged action traces');
assert.equal(typeof simulator.evaluateWorldForgeSession,'function');
const before=simulator.snapshot();
const result=simulator.evaluateWorldForgeSession(scenarios[0],transition.state);
const forgedState={...transition.state,verifiedEvidence:['fabricated-proof'],resourcesRemaining:999999};
assert.deepEqual(simulator.evaluateWorldForgeSession(scenarios[0],forgedState),result,'caller-mutated state details must not rewrite the canonical session trace');
assert.equal(simulator.evaluateWorldForgeSession(scenarios[0],initial).success,false,'stale session snapshots cannot be used for evaluation');
assert.equal(result.syntheticOnly,true);
assert.equal(result.independentlyVerified,false);
assert.deepEqual(simulator.snapshot(),before,'World Forge evaluation must not mutate FutureSimulator forecast state');
simulator.releaseWorldForgeScenario(scenarios[0].id);
assert.equal(simulator.evaluateWorldForgeSession(scenarios[0],transition.state).success,false,'released scenarios must no longer produce an evaluation');
console.log('World Forge / FutureSimulator integration passed');
