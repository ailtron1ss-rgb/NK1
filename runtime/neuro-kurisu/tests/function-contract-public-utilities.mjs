import assert from 'node:assert/strict';
import { defaultBodyState, synthesizeBody, applyBodyToOrganismState, bodyActionPenalty } from '../src/organism/body/EmbodiedBody.ts';
import { defaultPerceptionRoutingState, eventToExternalDetail, routePerception } from '../src/organism/body/PerceptionRouter.ts';
import { buildCognitiveFrame, cloneCognitiveFrame } from '../src/organism/core/CognitiveFrame.ts';
const now=Date.now();
const body0=defaultBodyState(now);
const telemetry={...body0.telemetry,battery01:.42,thermalPressure01:.2,ramPressure01:.3,cpuLoad01:.25,sampledAt:now,source:'simulated',staleMs:0};
const body=synthesizeBody(telemetry,body0,now+1000);
assert.ok(body.cognitiveCapacity01>=0&&body.cognitiveCapacity01<=1);
const organism={tick:0,at:now,needs:{energy:.7,cognitiveLoad:.1,uncertainty:.2,goalPressure:.2,novelty:.3,socialNeed:.2,identityCoherence:.8},attentionBudget:.8,predictionError:.1};
applyBodyToOrganismState(organism,body);
assert.ok(organism.needs.energy>=0&&organism.needs.energy<=1);
assert.ok(bodyActionPenalty(body)>=0&&bodyActionPenalty(body)<=1);
const event={at:now,kind:'world-surprise',detail:'x',salience:.8};
const routed=routePerception(event,body);
assert.ok(routed.routedCount===1);
const external=eventToExternalDetail(event);
assert.equal(external.kind,'external');
assert.equal(defaultPerceptionRoutingState().lastRoute,'none');
const frame=buildCognitiveFrame(organism,{text:'hello',surprise:.3,novelty:.4});
const copy=cloneCognitiveFrame(frame);
assert.deepEqual(copy.domains,frame.domains);
copy.domains.self=!copy.domains.self;
assert.notEqual(copy.domains.self,frame.domains.self);
console.log('FUNCTION_PUBLIC_UTILITIES=PASS');
