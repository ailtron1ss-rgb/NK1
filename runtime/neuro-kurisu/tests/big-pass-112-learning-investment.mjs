import assert from 'node:assert/strict';
import { P36AutonomousSelfDevelopmentEngine } from '../src/organism/learning/P36AutonomousSelfDevelopment.ts';
const e=new P36AutonomousSelfDevelopmentEngine();
const mk=(tick,overrides={})=>({tick,predictionError:.76,selfPredictionError:.45,autonomyScore:.58,attentionBudget:.79,needs:{energy:.86,cognitiveLoad:.18,uncertainty:.72,socialNeed:.24,novelty:.49,identityCoherence:.77,goalPressure:.42,...overrides}});
const invest=e.decideLearningInvestment(mk(8),{worldError01:.71,selfError01:.43,resourceRisk01:.16});
assert.equal(invest.decision,'invest');
assert.ok(invest.expectedGain01>invest.opportunityCost01);
const h=e.propose(mk(8),{worldError01:.71,selfError01:.43,resourceRisk01:.16});
assert.ok(h);
const before=e.snapshot().curriculum.mastery[h.area];
const low=e.decideLearningInvestment(mk(16,{energy:.12,cognitiveLoad:.82,uncertainty:.34}),{worldError01:.20,selfError01:.12,resourceRisk01:.88});
assert.equal(low.decision,'recover');
assert.equal(e.snapshot().curriculum.mastery[h.area],before);
const scarce=new P36AutonomousSelfDevelopmentEngine();
const scarceState=scarce.snapshot();
scarceState.learningBudget01=.10;
scarceState.spentBudget01=.08;
scarce.restore(scarceState);
const deferred=scarce.decideLearningInvestment(mk(24,{energy:.74,cognitiveLoad:.42,uncertainty:.18}),{worldError01:.08,selfError01:.08,resourceRisk01:.42});
assert.equal(deferred.decision,'defer');
assert.equal(scarce.snapshot().acceptedChanges,0);
const history=e.learningInvestmentHistory(8);
assert.ok(history.length>=2);
assert.ok(history.every(x=>x.reason.length>0));
console.log('BIG_PASS_112_LEARNING_INVESTMENT=PASS',JSON.stringify({investDecision:invest.decision,recoverDecision:low.decision,deferredDecision:deferred.decision,history:history.length,area:invest.area}));
