import assert from 'node:assert/strict';
import { performance } from 'node:perf_hooks';
import { OrganismCore } from '../src/organism/core/OrganismCore.ts';
import { MemoryStateStore } from '../src/organism/persistence/MemoryStateStore.ts';

const core=new OrganismCore(new MemoryStateStore(),{performanceProfile:'mobile',cycleResultMode:'operational',enableTemporalResolutionGovernor:true,operationalPulseEvery:4,checkpointMaxDirtyCycles:256,checkpointMinIntervalMs:600000});
await core.init();
const timings=[];
let full=0, verified=0;
for(let i=0;i<32;i++){
  const body={bodyEnergy01:.86-i*.004,cognitiveCapacity01:.86,thermalStrain01:i>24?.72:.18,sensoryFreshness01:.84,battery01:.80-i*.006,cpuLoad01:i>24?.74:.22,ramPressure01:i>24?.76:.18,awake:true};
  const external=i%2===0;
  const t=performance.now();
  const result=await core.observeOperational(external?{text:i%4===0?'Verify the uncertain consequence before committing.':'Explore the environment and revise from evidence.',novelty:i%7===0?.82:.38,surprise:i%9===0?.67:.16,embodiment:body}:{embodiment:body});
  timings.push(performance.now()-t);
  const isFull=result.workspace.content.temporalResolution!=='micro'; if(isFull)full++; if(!isFull)continue;
  const action=result.decision?.selected?.action??'wait';
  const reward=action==='verify'?.77:action==='explore'?.72:action==='reflect'?.68:action==='rest'?.69:.54;
  const world=i%4===0?{action,before:{tick:i,location:'critical-chain',energy:.81,attention:.73,uncertainty:.61,facts:[`before-${i}`],objects:[],events:[`before-${i}`]},after:{tick:i+1,location:'critical-chain',energy:.76,attention:.79,uncertainty:.32,facts:[`before-${i}`,`verified-${i}`],objects:[],events:[`before-${i}`,`after-${i}`]},reward,surprise:.12,at:Date.now()}:undefined;
  if(world)verified++;
  await core.feedback({success:reward,reward,surprise:.12,evidenceSource:world?'external':'unknown',worldTransition:world});
}
const b305=core.b305CriticalPathDiagnostics();
const b296=core.b296NeuralPersonalityAgencyDiagnostics();
const b299=core.b299CausalPersonalityDiagnostics();
const b302=core.b302LongHorizonDiagnostics();
assert.ok(full>=16,'B305 did not execute enough full cognitive pulses');
assert.ok(verified>=4,'B305 did not exercise enough verified world outcomes');
assert.ok(b296.learningUpdates>0,'B296 did not learn');
assert.ok(b296.synapticUpdates>0,'B296 synapses did not change');
assert.ok(b299.learningUpdates>=full,'B299 personality learning did not follow outcomes');
assert.ok(b302.verifiedUpdates>=verified,'B302 causal verified count is lower than injected verified outcomes');
assert.ok(b305.cycles>=full,'B305 did not observe critical path cycles');
assert.ok(b305.neuralUpdateCycles>0,'B305 neural edge never activated');
assert.ok(b305.causalBridgeCycles>0,'B305 causal edge never activated');
assert.ok(b305.personalityUpdateCycles>0,'B305 personality edge never activated');
assert.ok(b305.policyShiftCycles>0,'B305 policy edge never activated');
assert.ok(b305.verifiedOutcomeCycles>=verified,'B305 verified edge did not record outcomes');
assert.ok(b305.fullCriticalPath01>0.05,'B305 critical path evidence too weak');
const snap=core.snapshot();
const restored=new OrganismCore(new MemoryStateStore({initial:snap}),{performanceProfile:'mobile',cycleResultMode:'operational',enableTemporalResolutionGovernor:true,operationalPulseEvery:4,checkpointMaxDirtyCycles:256,checkpointMinIntervalMs:600000});
await restored.init();
const recovered=restored.b305CriticalPathDiagnostics();
assert.equal(recovered.cycles,b305.cycles,'B305 verification ledger lost after restart');
assert.equal(restored.b296NeuralPersonalityAgencyDiagnostics().learningUpdates,b296.learningUpdates,'B296 learning count lost after restart');
assert.equal(restored.b299CausalPersonalityDiagnostics().learningUpdates,b299.learningUpdates,'B299 learning count lost after restart');
const sorted=[...timings].sort((a,b)=>a-b);
const mean=timings.reduce((a,b)=>a+b,0)/Math.max(1,timings.length);
console.log(JSON.stringify({pass:true,ticks:core.snapshot().state.tick,full,verified,meanCycleMs:mean,p95CycleMs:sorted[Math.floor(sorted.length*.95)],b305, b296:{learningUpdates:b296.learningUpdates,synapticUpdates:b296.synapticUpdates},b299:{learningUpdates:b299.learningUpdates,personalityInfluence01:b299.personalityInfluence01},b302:{verifiedUpdates:b302.verifiedUpdates,consolidationWindows:b302.consolidationWindows},restart:true},null,2));
process.exit(0);
