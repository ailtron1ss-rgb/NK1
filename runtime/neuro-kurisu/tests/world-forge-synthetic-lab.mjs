import assert from 'node:assert/strict';
import { WorldForge } from '../src/organism/developmental/WorldForge.ts';
const forge=new WorldForge({maxCasesPerBatch:8});
const train=forge.generate({split:'train',seed:41,count:8,difficulty01:.6});
const trainAgain=forge.generate({split:'train',seed:41,count:8,difficulty01:.6});
const validation=forge.generate({split:'validation',seed:41,count:8,difficulty01:.6});
const holdout=forge.generate({split:'holdout',seed:41,count:8,difficulty01:.6});
assert.equal(train.length,8);assert.deepEqual(train,trainAgain);
assert.notDeepEqual(train.map(x=>x.id),validation.map(x=>x.id));
assert.notDeepEqual(train.map(x=>x.id),holdout.map(x=>x.id));
assert.ok(train.every(x=>x.syntheticOnly===true&&x.split==='train'));
assert.ok(holdout.every(x=>!('hiddenVariables'in x)&&!('answerKey'in x)&&!('requiredTargets'in x)));
assert.equal(forge.generate({split:'holdout',seed:-1,count:1}).length,0);
assert.equal(forge.generate({split:'holdout',seed:1,count:1000}).length,8);
const scenario=train[0];
assert.ok(Array.isArray(scenario.strategyFamilies)&&scenario.strategyFamilies.length>=2,'scenario should publish alternative strategy choices without an evaluator verdict field');
assert.equal('acceptedStrategyFamilies' in scenario,false,'public task metadata must not label hidden evaluator verdicts as accepted strategies');
const state=forge.startScenario(scenario);
assert.ok(state);
const alteredSplit=forge.evaluateSession({...scenario,split:'holdout'},state);
assert.equal(alteredSplit.success,false,'caller must not relabel a training scenario as holdout');
let goodState=forge.startScenario(scenario);
assert.ok(goodState);
for(const target of scenario.goalOptions.slice(0,2)){
 const transition=forge.step(goodState,{action:'inspect',target});
 assert.equal(transition.accepted,true);
 goodState=transition.state;
}
const observation=forge.step(goodState,{action:'observe'});
assert.equal(observation.accepted,true);
goodState=observation.state;
const good=forge.evaluateSession(scenario,goodState);
assert.equal(good.syntheticOnly,true);
assert.equal(good.independentlyVerified,false);
assert.ok(good.score01>=0&&good.score01<=1);
assert.ok(good.robustness01>=0&&good.robustness01<=1);
assert.ok(good.limitations.length>=2);
assert.ok(good.stepsUsed>=3);
forge.releaseEvaluator(scenario.id);
assert.equal(forge.evaluateSession(scenario,goodState).success,false,'released evaluator keys cannot score old sessions');
forge.reset();assert.equal(forge.evaluateSession(train[1],state).success,false);
console.log(JSON.stringify({ok:true,train:train.length,validation:validation.length,holdout:holdout.length,domains:[...new Set(train.map(x=>x.domain))]}));
