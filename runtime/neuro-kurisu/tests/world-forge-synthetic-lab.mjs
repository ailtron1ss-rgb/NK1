import assert from 'node:assert/strict';
import { WorldForge } from '../src/organism/developmental/WorldForge.ts';
const forge=new WorldForge({maxCasesPerBatch:8});
const train=forge.generate({split:'train',seed:41,count:8,difficulty01:.6});
const trainAgain=forge.generate({split:'train',seed:41,count:8,difficulty01:.6});
const validation=forge.generate({split:'validation',seed:41,count:8,difficulty01:.6});
const holdout=forge.generate({split:'holdout',seed:41,count:8,difficulty01:.6});
assert.equal(train.length,8);assert.deepEqual(train,trainAgain);
assert.notDeepEqual(train.map(x=>x.id),validation.map(x=>x.id));
assert.notDeepEqual(train.map(x=>x.id),holdout.map(x=>x.id));
assert.ok(train.every(x=>x.syntheticOnly===true&&x.split==='train'));
assert.ok(holdout.every(x=>!('hiddenVariables'in x)&&!('answerKey'in x)&&!('requiredTargets'in x)));
assert.equal(forge.generate({split:'holdout',seed:-1,count:1}).length,0);
assert.equal(forge.generate({split:'holdout',seed:1,count:1000}).length,8);
const scenario=train[0];
const invalid=forge.evaluate(scenario,[{action:'not-an-action'}]);
assert.equal(invalid.success,false);assert.equal(invalid.constraintViolations,1);
const good=forge.evaluate(scenario,[{action:'observe',target:'budget-check',evidence:'budget-check',cost:.2,risk01:.02},{action:'prioritize',target:'reserve',cost:.3,risk01:.03},{action:'verify',target:'allocate',evidence:'budget-check',cost:.2,risk01:.01}]);
assert.equal(good.syntheticOnly,true);assert.equal(good.independentlyVerified,false);
assert.ok(good.score01>=0&&good.score01<=1);assert.ok(good.robustness01>=0&&good.robustness01<=1);assert.ok(good.limitations.length>=2);
forge.releaseEvaluator(scenario.id);
assert.equal(forge.evaluate(scenario,[]).success,false);assert.equal(forge.evaluate(scenario,[]).score01,0);
forge.reset();assert.equal(forge.evaluate(train[1],[]).success,false);
console.log(JSON.stringify({ok:true,train:train.length,validation:validation.length,holdout:holdout.length,domains:[...new Set(train.map(x=>x.domain))]}));
