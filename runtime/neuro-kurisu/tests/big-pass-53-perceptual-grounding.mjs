import assert from 'node:assert/strict';
import { P41SemanticPerceptionEngine } from '../src/organism/cognition/P41SemanticPerception.ts';
import { P41NativePerceptionEngine } from '../src/organism/cognition/P41NativePerception.ts';
import { P41TemporalPerceptionModel } from '../src/organism/cognition/P41TemporalPerceptionModel.ts';
import { PerceptualEvidenceCompiler, defaultPerceptualEvidence } from '../src/organism/body/PerceptualEvidenceCompiler.ts';
import { MultimodalPerception } from '../src/organism/body/MultimodalPerception.ts';
const semantic=new P41SemanticPerceptionEngine();
const native=new P41NativePerceptionEngine();
const temporal=new P41TemporalPerceptionModel();
const multimodal=new MultimodalPerception();
assert.deepEqual(new PerceptualEvidenceCompiler().snapshot(),defaultPerceptualEvidence());
const rgb=[];for(let i=0;i<32*24;i++)rgb.push(220,120,80);
const ns=native.ingest({vision:{rawRgb:rgb,width:32,height:24},audio:{samples:Array.from({length:1024},(_,i)=>Math.sin(2*Math.PI*220*i/16000))},at:1000});
const ss=semantic.ingest({vision:{semantic:true,sceneLabel:'laboratory',confidence01:.86,objects:[{label:'terminal',confidence01:.9}],relations:[{from:'person',relation:'near',to:'terminal',confidence01:.8}]},sensor:{location:'lab',freshness01:.95},at:1000});
temporal.observe({scene:'laboratory',audioActivity01:ns.metrics.audioActivity01,visionChange01:ns.metrics.visionChange01,uncertainty01:.25,entities:ss.entities.length,cues:ns.semanticCues.slice(0,2).map(c=>c.label),at:1000});
multimodal.observe({modality:'vision',summary:'laboratory / terminal',confidence:.86,salience:.7,evidence:['camera'],content:'laboratory terminal'});
const compiler=new PerceptualEvidenceCompiler();
const out=compiler.compile({at:1100,multimodal:multimodal.snapshot(),semantic:semantic.snapshot(),native:native.snapshot(),temporal:temporal.snapshot()});
assert.equal(out.scene,'laboratory');
assert.ok(out.evidence.some(x=>x.claim==='entity:terminal'));
assert.ok(out.metrics.semanticCoverage01>0);
assert.ok(out.lastHash);
console.log(`BIG_PASS_53_PERCEPTUAL_GROUNDING=PASS evidence=${out.evidence.length} grounding=${out.metrics.grounding01.toFixed(3)} coverage=${out.metrics.semanticCoverage01.toFixed(3)} hash=${out.lastHash}`);
