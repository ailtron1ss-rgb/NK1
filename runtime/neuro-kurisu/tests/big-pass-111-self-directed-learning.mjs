import assert from 'node:assert/strict';
import { P36AutonomousSelfDevelopmentEngine } from '../src/organism/learning/P36AutonomousSelfDevelopment.ts';

const e=new P36AutonomousSelfDevelopmentEngine();
const mk=(tick,overrides={})=>({tick,predictionError:.74,selfPredictionError:.43,autonomyScore:.60,attentionBudget:.77,needs:{energy:.84,cognitiveLoad:.21,uncertainty:.70,socialNeed:.26,novelty:.50,identityCoherence:.78,goalPressure:.45,...overrides}});
const d1=e.selectDevelopmentFocus(mk(1),{worldError01:.72,selfError01:.44,resourceRisk01:.16});
assert.ok(d1.score01>0.36);
const h=e.propose(mk(2),{worldError01:.72,selfError01:.44,resourceRisk01:.16});
assert.ok(h);
assert.equal(e.learningAgenda().selectedArea,h.area);
const cycle=e.beginAutonomousDevelopmentCycle({hypothesisId:h.id,origin:'autonomous-gap'});
assert.ok(cycle);
const guarded=e.snapshot();
guarded.hypotheses=[{...h,status:'completed',evidenceGate:'holdout-verified'}];
guarded.currentHypothesisId=h.id;
guarded.agenda={...guarded.agenda,selectedArea:h.area,selectedHypothesisId:h.id};
const guardEngine=new P36AutonomousSelfDevelopmentEngine();
guardEngine.restore(guarded);
const repeated=guardEngine.propose(mk(3,{uncertainty:.18,goalPressure:.12}),{worldError01:.99,selfError01:.01,relationship01:.01,perception01:.01,resourceRisk01:.03});
assert.equal(repeated?.id,h.id);
const campaign=e.developmentCampaignPlan();
assert.ok(campaign.length>=cycle.requiredHoldout);
assert.ok(campaign.every(x=>x.hypothesisId===h.id));
assert.equal(campaign.filter(x=>x.holdout).length,cycle.requiredHoldout);
assert.ok(campaign.every(x=>x.phase!=='delayed-test'||x.delayMs>0));
const bias=e.developmentTaskBias(cycle.requestedAction);
assert.ok(bias>e.developmentTaskBias('respond'));
const before=e.learningAgenda().selectionCount;
const d2=e.selectDevelopmentFocus(mk(3),{worldError01:.72,selfError01:.44,resourceRisk01:.16});
assert.ok(d2.area!==undefined);
assert.equal(e.learningAgenda().selectionCount,before);
assert.ok(d2.score01>=0 && d2.score01<=1);
for(let i=0;i<6;i++) e.recordExternalEvidence({hypothesisId:h.id,contextKey:`ctx-${i<2?'a':i<4?'b':'c'}`,control01:.50,treatment01:.60,independentVerified:true,holdout:i>=1,delayMs:1000*(i+1),evaluatorVersion:'real-evaluator-v2',evidenceSource:'external-evaluator',protocolId:'real-protocol-111',sessionId:'real-session-111',trialId:`t-${i}`,at:100+i});
const snap=e.snapshot();
assert.equal(snap.acceptedChanges,1);
assert.equal(snap.agenda.selectedHypothesisId,null);
assert.equal(snap.hypotheses[0].evidenceGate,'replicated');
console.log('BIG_PASS_111_SELF_DIRECTED_LEARNING=PASS',JSON.stringify({area:d1.area,score01:Number(d1.score01.toFixed(3)),stage:snap.developmentCycles[0].stage,acceptedChanges:snap.acceptedChanges,selectionCount:snap.agenda.selectionCount,campaignSlots:campaign.length}));
