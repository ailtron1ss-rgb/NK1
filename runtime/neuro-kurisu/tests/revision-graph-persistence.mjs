import assert from 'node:assert/strict';
import { OrganismCore } from '../src/organism/core/OrganismCore.ts';
import { MemoryStateStore } from '../src/organism/persistence/MemoryStateStore.ts';
const store=new MemoryStateStore();
const core=new OrganismCore(store,{checkpointMaxDirtyCycles:8,checkpointMinIntervalMs:60000});
await core.init();
let r=core.revisionGraphSnapshot();
assert.equal(r.current.critical,0);
await core.observe({text:'revision graph memory proof'});
r=core.revisionGraphSnapshot();
assert.ok(r.current.critical>=1);
assert.ok(r.current.memory>=1);
assert.ok(r.current.identity>=1);
assert.ok(r.current.developmental>=1);
assert.ok(r.current.reality===0);
assert.equal(r.current.reality,r.materialized.reality);
await core.flush();
const persisted=await store.load();
assert.ok(persisted?.system.revisionGraph);
assert.ok(persisted?.system.revisionTokens);
assert.equal(persisted.system.revisionGraph.current.critical,persisted.system.revisionGraph.materialized.critical);
assert.equal(persisted.system.revisionGraph.current.memory,persisted.system.revisionGraph.materialized.memory);
const tokens=persisted.system.revisionTokens.tokens;
assert.equal(tokens['memory-core'].revision,tokens['memory-core'].materializedRevision);
assert.equal(tokens['memory-fabric'].revision,tokens['memory-fabric'].materializedRevision);
assert.ok(tokens['memory-core'].revision>=1);
assert.ok(tokens['memory-fabric'].revision===0);
console.log('REVISION_GRAPH_PERSISTENCE=PASS',JSON.stringify({graph:persisted.system.revisionGraph,tokens:{memoryCore:tokens['memory-core'],memoryFabric:tokens['memory-fabric']}}));
