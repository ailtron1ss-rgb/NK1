import assert from 'node:assert/strict';
import { OpenLoopRadar, defaultOpenLoopRadarState } from '../src/organism/cognition/evolution/OpenLoopRadar.ts';
let now = 1800000000000;
const radar = new OpenLoopRadar(() => now);
assert.deepEqual(radar.snapshot(), defaultOpenLoopRadarState());
assert.throws(() => radar.register({title:'Unaccepted',kind:'promise',owner:'system',accepted:false,source:'test'}), /explicit-acceptance-required/);
const prerequisite = radar.register({title:'Wait for provider response',kind:'waiting',owner:'system',accepted:true,source:'test',dueAt:now+60000,priority:0.7});
const dependent = radar.register({title:'Finish integration',kind:'project_step',owner:'system',accepted:true,source:'test',dependencies:[prerequisite.id],dueAt:now+120000,priority:0.9});
assert.equal(dependent.status,'blocked');
now += 61000;
const due = radar.scan({now,dueSoonMs:120000,reminderCooldownMs:0});
assert.equal(due.find(x=>x.record.id===prerequisite.id)?.surfaceReason,'overdue');
assert.equal(due.find(x=>x.record.id===prerequisite.id)?.shouldSurface,true);
assert.throws(()=>radar.fulfill(prerequisite.id,{kind:'user-confirmation',reference:'',verifiedAt:now}),/valid-closure-evidence-required/);
assert.throws(()=>radar.fulfill(prerequisite.id,{kind:'execution-receipt',reference:'future',verifiedAt:now+1}),/closure-evidence-cannot-be-from-the-future/);
radar.fulfill(prerequisite.id,{kind:'external-confirmation',reference:'ticket:42',verifiedAt:now});
assert.equal(radar.snapshot().records.find(x=>x.id===dependent.id)?.status,'open');
assert.equal(radar.scan({now,quietUntil:now+60000,reminderCooldownMs:0}).find(x=>x.record.id===dependent.id)?.shouldSurface,false);
radar.markSurfaced(dependent.id);
assert.equal(radar.scan({now,reminderCooldownMs:60000}).find(x=>x.record.id===dependent.id)?.shouldSurface,false);
const before=radar.snapshot();
assert.throws(()=>radar.fulfill(dependent.id,{kind:'user-confirmation',reference:'done',verifiedAt:now}),/open-loop-already-closed/);
const restored=new OpenLoopRadar(()=>now); restored.restore(before);
assert.deepEqual(restored.snapshot(),before);
const tampered={version:1,sequence:'999',records:[before.records[0],{...before.records[1],status:'fulfilled',closureEvidence:null},{...before.records[1],accepted:false}]};
restored.restore(tampered); assert.equal(restored.snapshot().records.length,1);
const cancellable=restored.register({title:'Optional research',kind:'task',owner:'user',accepted:true,source:'test'});
assert.throws(()=>restored.cancel(cancellable.id,' '),/cancellation-reason-required/);
restored.cancel(cancellable.id,'No longer relevant');
assert.throws(()=>restored.reopen(cancellable.id,''),/reopen-reason-required/);
restored.reopen(cancellable.id,'Scope changed');
assert.equal(restored.snapshot().records.find(x=>x.id===cancellable.id)?.status,'open');
const expired=restored.register({title:'Temporary',kind:'waiting',owner:'system',accepted:true,source:'test',expiresAt:now-1});
assert.equal(restored.scan({now,reminderCooldownMs:0}).find(x=>x.record.id===expired.id)?.effectiveStatus,'expired');
const detached=restored.snapshot(); detached.records[0].title='tampered';
assert.notEqual(restored.snapshot().records[0].title,'tampered');
console.log('OPEN_LOOP_RADAR_CONTRACT=PASS');
