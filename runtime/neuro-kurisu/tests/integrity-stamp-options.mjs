import assert from 'node:assert/strict';
import { IntegritySentinel } from '../src/organism/system/IntegritySentinel.ts';
import { RELEASE_CONTRACT } from '../src/organism/system/ReleaseContract.ts';
import { OrganismCore } from '../src/organism/core/OrganismCore.ts';
import { MemoryStateStore } from '../src/organism/persistence/MemoryStateStore.ts';
const sentinel=new IntegritySentinel();
const core=new OrganismCore(new MemoryStateStore(),{cycleResultMode:'operational'});
await core.init();
const state=core.persisted;
const integrity=sentinel.check(state);
assert.equal(integrity.ok,true);
const stamped=sentinel.stamp(state,{...state.system.capabilities},integrity,{clone:false,hash:true});
const durableHash=stamped.system.lastStateHash;
assert.ok(durableHash.length>0);
stamped.state.tick += 1;
const hot=sentinel.stamp(stamped,{...stamped.system.capabilities},sentinel.check(stamped),{clone:false,hash:false});
assert.equal(hot.system.lastStateHash,durableHash,'hot stamp must preserve last durable hash');
const durable=sentinel.stamp(hot,{...hot.system.capabilities},sentinel.check(hot),{clone:false,hash:true});
assert.notEqual(durable.system.lastStateHash,durableHash,'durable stamp must refresh hash after mutation');
assert.equal(durable.system.schemaVersion,RELEASE_CONTRACT.stateSchema);
console.log('INTEGRITY_STAMP_OPTIONS=PASS');
