import assert from 'node:assert/strict';
import { P84AutobiographicalContinuityFabric } from '../src/organism/developmental/P84AutobiographicalContinuityFabric.ts';
const f=new P84AutobiographicalContinuityFabric();
const base={goalFamily:'epistemic',uncertainty01:.82,novelty01:.74,energy01:.81,cognitiveLoad01:.28,realityConfidence01:.78};
const near={...base,uncertainty01:.58};
for(let i=0;i<3;i++) f.learnFromVerifiedOutcome({action:'explore',success01:1,confidence01:.95,evidence01:.96,at:1000+i,context:base});
const exact=f.actionBias('explore',2000,base);
const nearby=f.actionBias('explore',2000,near);
assert(exact>0,'exact context must learn positive bias');
assert(nearby>0 && nearby<exact,'nearby context must receive attenuated transfer');
const neg=new P84AutobiographicalContinuityFabric();
for(let i=0;i<3;i++) neg.learnFromVerifiedOutcome({action:'verify',success01:0,confidence01:.95,evidence01:.96,at:1000+i,context:base});
const negExact=neg.actionBias('verify',2000,base);
assert(negExact<0,'verified negative experience must remain signed');
const restored=new P84AutobiographicalContinuityFabric();
restored.restore(f.snapshot());
assert.equal(restored.snapshot().version,6);
assert(Math.abs(restored.actionBias('explore',2000,base)-exact)<1e-12);
console.log(`BIG_PASS_71_SIMILARITY_TRANSFER=PASS exact=${exact.toFixed(4)} nearby=${nearby.toFixed(4)} negative=${negExact.toFixed(4)}`);
