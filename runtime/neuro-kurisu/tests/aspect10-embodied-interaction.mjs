import assert from 'node:assert/strict';
import { EmbodiedInteractionController } from '../src/organism/body/EmbodiedInteractionController.ts';
const now=10_000;
const target={id:'cup-01',label:'ceramic cup',position:{x:.35,y:1.1,z:.2},frameId:'avatar-root-m',confidence01:.96,visible:true,observedAt:now,source:'camera',safeToTouch:true,affordances:['grasp','release'],radiusM:.05};
const body={frameId:'avatar-root-m',head:{x:0,y:1.65,z:0},leftHand:{x:-.25,y:1,z:0},rightHand:{x:.25,y:1,z:0},reachM:1,energy01:.9,awake:true};
const safe=new EmbodiedInteractionController({allowContact:true,allowManipulation:true});
const look=safe.plan({target,body,kind:'look',now});
assert.equal(look.accepted,true);
assert.equal(look.next?.hand,'none');
const grasp=safe.plan({target,body,kind:'grasp',now,hand:'right'});
assert.equal(grasp.accepted,true);
assert.equal(grasp.next?.requiresAdapter,true);
assert.equal(grasp.next?.requiresPostcondition,true);
assert.equal(safe.assessExecution({planId:grasp.next.id,status:'executed',postcondition:'missing'}).phase,'uncertain');
const retry=safe.plan({target,body,kind:'grasp',now:now+1,hand:'right'});
assert.equal(safe.assessExecution({planId:retry.next.id,status:'executed',postcondition:'verified',observedTargetId:'other'}).accepted,false);
const verified=safe.assessExecution({planId:retry.next.id,status:'executed',postcondition:'verified',observedTargetId:target.id});
assert.equal(verified.phase,'completed');
const deniedFrame=new EmbodiedInteractionController();
assert.equal(deniedFrame.plan({target,body:{...body,frameId:'camera-local'},kind:'look',now}).reason,'spatial-coordinate-frame-mismatch');
const denied=new EmbodiedInteractionController();
assert.equal(denied.plan({target:{...target,source:'simulator'},body,kind:'touch',now}).reason,'contact-requires-live-camera-grounding');
assert.equal(denied.plan({target,body,kind:'touch',now}).reason,'contact-not-explicitly-authorized');
assert.equal(denied.plan({target:{...target,label:'hot chemical container'},body,kind:'touch',now}).reason,'hazardous-or-unknown-object-contact-denied');
assert.equal(denied.plan({target:{...target,observedAt:now-9000},body,kind:'look',now}).reason,'stale-or-future-observation');
assert.equal(denied.plan({target:{...target,confidence01:.2},body,kind:'look',now}).accepted,false);
assert.equal(safe.plan({target,body:{...body,reachM:.05},kind:'grasp',now}).reason,'target-outside-arm-reach');
assert.equal(safe.assessExecution({planId:'old-plan',status:'executed',postcondition:'verified'}).reason,'stale-or-unknown-plan-id');
console.log(JSON.stringify({pass:true,tests:12,coverage:['grounded-look','reachability','contact-policy','hazard-denial','freshness','confidence','affordance','adapter-gate','postcondition-required','target-binding','idempotent-plan-identity','stale-plan-rejection']}));
