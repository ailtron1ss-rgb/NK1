import assert from 'node:assert/strict';
import { P30ContinualIntelligenceEngine } from '../src/organism/learning/P30ContinualIntelligence.ts';
const mk=(taskId,action,outcome,energy=.72)=>({taskId,action,outcome,state:{version:122,tick:1,at:Date.now(),needs:{energy,cognitiveLoad:.24,uncertainty:.46,novelty:.62,socialNeed:.28,identityCoherence:.81,goalPressure:.64},predictionError:.32,attentionBudget:.76,lastAction:action,lastActionSuccess:outcome,autonomyScore:.72,selfPredictionError:.24,predictedNextAction:action,lastPredictionConfidence:.72,worldContextVersion:1}});
const e=new P30ContinualIntelligenceEngine();
for(let i=0;i<8;i++) e.recordTaskScore('source-task',.86,mk('source-task','explore',.86,.70+i*.006).state,'explore');
for(let i=0;i<8;i++) e.recordTaskScore('source-task-2',.80,mk('source-task-2','explore',.80,.72+i*.004).state,'explore');
const target=mk('new-task','explore',.5,.73).state;
const before=e.transferBias(target,'new-task','explore');
assert.equal(before.eligible,true);
assert.ok(before.bias01>0);
assert.ok(before.similarity01>=.72);
e.noteTransferApplication(before);
for(let i=0;i<4;i++) e.recordTaskScore('new-task',.84,target,'explore');
const d=e.diagnostics();
assert.ok(d.transfer.exemplars>=3);
assert.ok(d.metrics.transferApplications>=1);
assert.ok(d.metrics.positiveTransferApplications>=1);
const negative=new P30ContinualIntelligenceEngine();
for(let i=0;i<8;i++) negative.recordTaskScore('bad-source',.18,mk('bad-source','verify',.18,.73).state,'verify');
const negativeBias=negative.transferBias(mk('fresh','verify',.5,.73).state,'fresh','verify');
assert.ok(negativeBias.bias01<0);
negative.noteTransferApplication(negativeBias);
assert.ok(negative.diagnostics().metrics.negativeTransferApplications>=1);
console.log(`BIG_PASS_116=PASS transferBias=${before.bias01.toFixed(4)} similarity=${before.similarity01.toFixed(3)} applications=${d.metrics.transferApplications}`);
