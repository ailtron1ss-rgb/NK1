import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const readJson = async p => JSON.parse(await readFile(path.join(ROOT,p),'utf8'));
const version = await readJson('VERSION.json');
const manifest = await readJson('RELEASE_MANIFEST.json');
const pkg = await readJson('package.json');
const lock = await readJson('package-lock.json');
const errors=[];
for (const [k,v] of [['version',version.application],['version',manifest.version],['version',pkg.version],['lock.version',lock.packages?.['']?.version]]) if(v!==version.application) errors.push(`${k} mismatch: ${v}`);
if(version.version!==version.application) errors.push(`VERSION.json.version alias mismatch: ${version.version}`);
if(manifest.organismCore!==version.organismCore) errors.push('manifest.organismCore mismatch');
if(manifest.stateSchema!==version.stateSchema) errors.push('manifest.stateSchema mismatch');
if(manifest.phase!==version.phase) errors.push('manifest.phase mismatch');
if(lock.lockfileVersion!==3) errors.push('lockfileVersion must be 3');
if(Object.keys(lock.packages||{}).length!==1) errors.push('lockfile must contain zero external packages');
if(!pkg.scripts['release:audit']) errors.push('missing release:audit');
if(pkg.scripts['release:audit'].includes('research:')) errors.push('release:audit must not run research suites');
console.log(errors.length ? `RELEASE_CONTRACT=FAIL\n${errors.join('\n')}` : 'RELEASE_CONTRACT=PASS');
if(errors.length) process.exit(1);
