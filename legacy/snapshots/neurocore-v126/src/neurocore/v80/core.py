def _norm(x: Tensor) -> Tensor:
    return F.normalize(x, dim=-1)


@dataclass
class V80Config(V79Config):
    """V80: a real differentiable learning spine over the compact predictive core.

    V80 is intentionally a learning-path consolidation pass, not another memory store.
    The canonical V61 memory remains the only neural-memory owner. Legacy inherited modules
    remain available for runtime compatibility but are frozen unless explicitly promoted into
    the current learning spine.
    """

    unified_hidden_v80: int = 64
    unified_context_dim_v80: int = 54
    unified_learning_lr_v80: float = 3e-4
    unified_memory_loss_weight_v80: float = 0.55
    unified_predictive_loss_weight_v80: float = 1.0
    unified_world_loss_weight_v80: float = 0.55
    unified_spine_loss_weight_v80: float = 0.45
    unified_cross_system_weight_v80: float = 0.12
    unified_temporal_weight_v80: float = 0.04
    unified_replay_loss_weight_v80: float = 0.25
    unified_replay_base_mix_v80: float = 0.25
    unified_replay_conflict_gain_v80: float = 0.35
    unified_gradient_clip_v80: float = 1.0
    unified_freeze_legacy_v80: bool = True
    unified_strategy_version_v80: int = 1


def mobile_v80_config(raw_observation_dim: int = 9) -> V80Config:
    base = dict(mobile_v79_config(raw_observation_dim).__dict__)
    base.update({
        "unified_hidden_v80": 64,
        "unified_context_dim_v80": 54,
        "unified_learning_lr_v80": 3e-4,
        "unified_memory_loss_weight_v80": 0.55,
        "unified_predictive_loss_weight_v80": 1.0,
        "unified_world_loss_weight_v80": 0.55,
        "unified_spine_loss_weight_v80": 0.45,
        "unified_cross_system_weight_v80": 0.12,
        "unified_temporal_weight_v80": 0.04,
        "unified_replay_loss_weight_v80": 0.25,
        "unified_replay_base_mix_v80": 0.25,
        "unified_replay_conflict_gain_v80": 0.35,
        "unified_gradient_clip_v80": 1.0,
        "unified_freeze_legacy_v80": True,
        "unified_strategy_version_v80": 1,
    })
    return V80Config(**base)


class UnifiedLearningSpineV80(nn.Module):
    """Shared differentiable state that couples prediction, memory and dynamics.

    Inputs are generated by real V46/V47 predictive cores and the V50 latent world model.
    Outputs are consumed by canonical V61 memory and by the predictive objective. The module
    therefore cannot be a dead feature: its state creates the memory context that is optimized
    jointly with the predictive/world-model losses.
    """

    def __init__(self, feature_dim: int, hidden: int, context_dim: int, latent_dim: int):
        super().__init__()
        self.feature_dim = int(feature_dim)
        self.hidden = int(hidden)
        self.context_dim = int(context_dim)
        self.latent_dim = int(latent_dim)
        self.input_norm = nn.LayerNorm(self.feature_dim)
        self.input_proj = nn.Sequential(
            nn.Linear(self.feature_dim, self.hidden), nn.SiLU(),
            nn.Linear(self.hidden, self.hidden), nn.SiLU(),
        )
        self.state_cell = nn.GRUCell(self.hidden, self.hidden)
        self.next_latent_head = nn.Sequential(
            nn.Linear(self.hidden, self.hidden), nn.SiLU(),
            nn.Linear(self.hidden, self.latent_dim),
        )
        self.memory_context_head = nn.Sequential(
            nn.Linear(self.hidden, self.hidden), nn.SiLU(),
            nn.Linear(self.hidden, self.context_dim),
        )
        self.confidence_head = nn.Sequential(nn.Linear(self.hidden, 1), nn.Sigmoid())
        self.memory_to_action = nn.Sequential(
            nn.Linear(20, self.hidden), nn.SiLU(),
            nn.Linear(self.hidden, 3), nn.Tanh(),
        )

    def step(self, features: Tensor, state: Optional[Tensor] = None) -> Dict[str, Tensor]:
        if features.ndim != 2 or features.size(-1) != self.feature_dim:
            raise ValueError(f"expected [B,{self.feature_dim}] features")
        projected = self.input_proj(self.input_norm(features))
        if state is None:
            state = projected.new_zeros(projected.size(0), self.hidden)
        state = self.state_cell(projected, state)
        next_latent = _norm(self.next_latent_head(state))
        context = self.memory_context_head(state)
        confidence = self.confidence_head(state)
        return {
            "state": state,
            "next_latent": next_latent,
            "memory_context": context,
            "confidence": confidence,
        }

    def forward(self, features: Tensor) -> Dict[str, Tensor]:
        if features.ndim != 3 or features.size(-1) != self.feature_dim:
            raise ValueError(f"expected [B,T,{self.feature_dim}] features")
        state = None
        rows = []
        for i in range(features.size(1)):
            out = self.step(features[:, i], state)
            state = out["state"]
            rows.append(out)
        return {k: torch.stack([r[k] for r in rows], dim=1) for k in rows[0]}


class NeuroWeaveV80(NeuroWeaveV79):
    """V80 current learning trunk.

    The inherited V79 runtime remains available, but V80 introduces an explicit differentiable
    sequence-learning path that directly trains the compact predictive brain, world model,
    canonical memory, and shared learning spine with one optimizer. Legacy modules are frozen
    by default instead of pretending that every historical subsystem participates in learning.
    """

    FEATURE_DIM_V80 = 32 + 20 + 24 + 20 + 20 + 3 + 3 + 1 + 1 + 9 + 8

    def __init__(self, cfg: Optional[V80Config] = None):
        cfg = cfg or mobile_v80_config(9)
        super().__init__(cfg)
        self.cfg = cfg
        memory_dim = int(self.neural_memory_v61.input_dim)
        if int(cfg.unified_context_dim_v80) != memory_dim:
            cfg.unified_context_dim_v80 = memory_dim
        self.unified_spine_v80 = UnifiedLearningSpineV80(
            feature_dim=self.FEATURE_DIM_V80,
            hidden=cfg.unified_hidden_v80,
            context_dim=cfg.unified_context_dim_v80,
            latent_dim=cfg.latent_dim_v46,
        )
        self._configure_current_learning_contract_v80()

    @property
    def neural_memory_v79(self):
        return self.neural_memory_v61

    @property
    def neural_memory_v80(self):
        return self.neural_memory_v61

    def _configure_current_learning_contract_v80(self) -> None:
        active_roots = (
            "brain46.",
            "brain47.",
            "world_model_v50.",
            "neural_memory_v61.",
            "unified_spine_v80.",
        )
        for name, param in self.named_parameters():
            keep = any(name.startswith(prefix) for prefix in active_roots)
            if name.startswith("brain46.target_encoder.") or name.startswith("brain47.target_encoder."):
                keep = False
            if name.startswith("target47."):
                keep = False
            if self.cfg.unified_freeze_legacy_v80:
                param.requires_grad_(keep)
        self._active_learning_parameter_names_v80 = [
            name for name, p in self.named_parameters() if p.requires_grad
        ]

    def learning_parameter_report_v80(self) -> Dict[str, float]:
        total = sum(p.numel() for p in self.parameters())
        active = sum(p.numel() for p in self.parameters() if p.requires_grad)
        return {
            "total_parameters": float(total),
            "active_parameters": float(active),
            "active_fraction": float(active / max(1, total)),
            "frozen_parameters": float(total - active),
        }

    @staticmethod
    def _goal_sequence(goal: Optional[Tensor], x: Tensor) -> Tensor:
        if goal is None:
            return x.new_zeros(x.size(0), x.size(1), 8)
        return goal

    def forward_learning_v80(
        self,
        x: Tensor,
        goal_sequence: Optional[Tensor] = None,
        *,
        target_latent_sequence: Optional[Tensor] = None,
    ) -> Dict[str, Tensor]:
        """Fully differentiable end-to-end learning path.

        Unlike the historical organism runtime, this path intentionally does not call the
        no-grad planner/action admission stack. It trains the compact predictive substrate and
        canonical memory directly, while preserving that stack as the inference/runtime surface.
        """
        if x.ndim != 3:
            raise ValueError("x must be [B,T,D]")
        b, t, _ = x.shape
        goals = goal_sequence if goal_sequence is not None else x.new_zeros(b, t, self.cfg.goal_dim)
        if goals.shape != (b, t, self.cfg.goal_dim):
            raise ValueError("goal_sequence shape mismatch")

        h46 = self.brain46.initial(b, x.device, x.dtype)
        fast47 = self.brain47.initial_fast(b, x.device, x.dtype)
        slow47 = self.brain47.initial_slow(b, x.device, x.dtype)
        world_h = self.world_model_v50.initial_hidden(b, x.device, x.dtype)
        spine_state = x.new_zeros(b, self.cfg.unified_hidden_v80)
        memory_prior = x.new_zeros(b, self.cfg.action_dim)
        action_prev = x.new_zeros(b, self.cfg.action_dim)

        feature_rows = []
        b46_rows, b47_rows, world_rows = [], [], []
        memory_rows, spine_rows = [], []
        memory_context_rows, memory_prior_rows = [], []
        for i in range(t):
            obs_t = x[:, i]
            goal_t = goals[:, i]
            brain46 = self.brain46(
                obs_t, h46, action_prev if i > 0 else memory_prior, goal_t,
                memory_prior=memory_prior,
                planner_strength=1.0,
            )
            h46 = brain46["hidden"]
            brain47 = self.brain47(
                obs_t, fast47, slow47, brain46["action"], goal_t, i + 1,
                memory_prior=memory_prior,
                planning_strength=1.0,
            )
            fast47 = brain47["fast_hidden"]
            slow47 = brain47["slow_hidden"]
            action_prev = brain47["action"]
            goal_latent = self.brain46.goal_latent(goal_t)
            world = self.world_model_v50.step(
                brain47["current_latent"], brain47["action"], goal_latent, world_h, horizon=1
            )
            world_h = world["hidden"]
            features = torch.cat([
                brain46["hidden"],
                brain47["current_latent"],
                brain47["workspace"],
                brain47["predicted_latent"],
                world["next_latent"],
                brain47["action"],
                memory_prior,
                world["horizon_uncertainty"],
                brain47["confidence"],
                obs_t,
                goal_t,
            ], dim=-1)
            spine = self.unified_spine_v80.step(features, spine_state)
            spine_state = spine["state"]
            mem_out = self.neural_memory_v61(spine["memory_context"])
            memory_read = mem_out["read"]
            memory_prior = 0.25 * torch.tanh(self.unified_spine_v80.memory_to_action(memory_read[..., :20]))
            feature_rows.append(features)
            b46_rows.append(brain46)
            b47_rows.append(brain47)
            world_rows.append(world)
            memory_rows.append(memory_read)
            spine_rows.append(spine)
            memory_context_rows.append(spine["memory_context"])
            memory_prior_rows.append(memory_prior)

        features = torch.stack(feature_rows, dim=1)
        spine = {k: torch.stack([r[k] for r in spine_rows], dim=1) for k in spine_rows[0]}
        memory_read_seq = torch.stack(memory_rows, dim=1)
        memory_context_seq = torch.stack(memory_context_rows, dim=1)
        memory_prior_seq = torch.stack(memory_prior_rows, dim=1)

        if target_latent_sequence is None:
            next_targets = []
            with torch.no_grad():
                for i in range(t - 1):
                    next_targets.append(self.brain46.target_latent(x[:, i + 1], goals[:, i + 1]))
                if next_targets:
                    target_next = torch.stack(next_targets, dim=1)
                else:
                    target_next = x.new_zeros(b, 0, self.cfg.latent_dim_v46)
        else:
            target_next = target_latent_sequence
            if target_next.ndim != 3 or target_next.shape[:2] != (b, t - 1):
                raise ValueError("target_latent_sequence must be [B,T-1,L]")

        if t < 2:
            zero = x.new_zeros(())
            return {
                "loss": zero,
                "memory_loss": zero,
                "predictive_loss": zero,
                "world_loss": zero,
                "spine_loss": zero,
                "cross_system_loss": zero,
                "temporal_loss": zero,
                "features": features,
                "spine_state": spine["state"],
                "spine_next_latent": spine["next_latent"],
                "memory_context": memory_context_seq,
                "memory_read": memory_read_seq,
                "memory_prior": memory_prior_seq,
            }

        slice_ctx = memory_context_seq[:, :-1].reshape(-1, self.neural_memory_v61.input_dim)
        flat_target = target_next.reshape(-1, target_next.size(-1))
        mem_parts = self.neural_memory_v61.memory_loss(slice_ctx, flat_target)
        memory_loss = mem_parts["loss"]

        world_pred = torch.stack([r["next_latent"] for r in world_rows[:-1]], dim=1)
        brain_pred = torch.stack([r["predicted_latent"] for r in b47_rows[:-1]], dim=1)
        spine_pred = spine["next_latent"][:, :-1]
        target = _norm(target_next.detach())
        predictive_loss = (1.0 - F.cosine_similarity(brain_pred, target, dim=-1)).mean()
        world_loss = (1.0 - F.cosine_similarity(world_pred, target, dim=-1)).mean()
        spine_loss = (1.0 - F.cosine_similarity(spine_pred, target, dim=-1)).mean()
        cross_system_loss = F.smooth_l1_loss(_norm(world_pred), _norm(spine_pred).detach())
        temporal_loss = (spine["state"][:, 1:] - spine["state"][:, :-1].detach()).pow(2).mean()
        total = (
            self.cfg.unified_memory_loss_weight_v80 * memory_loss
            + self.cfg.unified_predictive_loss_weight_v80 * predictive_loss
            + self.cfg.unified_world_loss_weight_v80 * world_loss
            + self.cfg.unified_spine_loss_weight_v80 * spine_loss
            + self.cfg.unified_cross_system_weight_v80 * cross_system_loss
            + self.cfg.unified_temporal_weight_v80 * temporal_loss
        )
        return {
            "loss": total,
            "memory_loss": memory_loss,
            "predictive_loss": predictive_loss,
            "world_loss": world_loss,
            "spine_loss": spine_loss,
            "cross_system_loss": cross_system_loss,
            "temporal_loss": temporal_loss,
            "features": features,
            "spine_state": spine["state"],
            "spine_next_latent": spine["next_latent"],
            "memory_context": memory_context_seq,
            "memory_read": memory_read_seq,
            "memory_prior": memory_prior_seq,
        }


class OrganismTrainerV80(OrganismTrainerV79):
    """Single-optimizer trainer for the current differentiable learning trunk."""

    def __init__(self, model: NeuroWeaveV80, lr: Optional[float] = None, warmup_steps: int = 4, external_verifier=None):
        super().__init__(model, lr=lr or model.cfg.unified_learning_lr_v80, warmup_steps=warmup_steps, external_verifier=external_verifier)
        self.model: NeuroWeaveV80 = model
        self.unified_optimizer_v80 = torch.optim.AdamW(
            [p for p in model.parameters() if p.requires_grad],
            lr=lr or model.cfg.unified_learning_lr_v80,
            weight_decay=1e-4,
        )
        self.unified_steps_v80 = 0

    def _gradient_coverage_v80(self) -> Dict[str, float]:
        active = [(n, p) for n, p in self.model.named_parameters() if p.requires_grad]
        nonzero = [p for _, p in active if p.grad is not None and torch.isfinite(p.grad).all() and float(p.grad.abs().sum().item()) > 0.0]
        total_numel = sum(p.numel() for _, p in active)
        nonzero_numel = sum(p.numel() for p in nonzero)
        return {
            "active_parameter_count": float(len(active)),
            "nonzero_parameter_count": float(len(nonzero)),
            "gradient_coverage": float(nonzero_numel / max(1, total_numel)),
        }

    def learning_step_v80(
        self,
        x: Tensor,
        goal_sequence: Optional[Tensor] = None,
        *,
        target_latent_sequence: Optional[Tensor] = None,
    ) -> Dict[str, float]:
        self.model.train()
        out = self.model.forward_learning_v80(
            x, goal_sequence=goal_sequence, target_latent_sequence=target_latent_sequence
        )
        active = [p for p in self.model.parameters() if p.requires_grad]
        self.unified_optimizer_v80.zero_grad(set_to_none=True)
        out["loss"].backward(retain_graph=True)
        base_grads = [p.grad.detach().clone() if p.grad is not None else None for p in active]

        replay_batch = self.model.neural_memory_v61._replay_batch()
        replay_loss = x.new_zeros(())
        replay_grads = [None for _ in active]
        replay_cosine = 0.0
        replay_mix = 0.0
        projection_ratio = 0.0
        replay_grad_norm = 0.0
        replay_available = 0.0
        if replay_batch is not None:
            replay_available = 1.0
            rctx, rtgt = replay_batch
            replay_parts = self.model.neural_memory_v61.memory_loss(rctx, rtgt)
            replay_loss = replay_parts["loss"]
            self.unified_optimizer_v80.zero_grad(set_to_none=True)
            (self.model.cfg.unified_replay_loss_weight_v80 * replay_loss).backward()
            replay_grads = [p.grad.detach().clone() if p.grad is not None else None for p in active]
            _, base_norm, replay_norm, replay_cosine = self._global_gradient_stats_v78(base_grads, replay_grads)
            replay_grad_norm = replay_norm
            replay_mix = self.adaptive_replay_mix_v78(
                self.model.cfg.unified_replay_base_mix_v80,
                replay_cosine,
                gain=self.model.cfg.unified_replay_conflict_gain_v80,
            )

        self.unified_optimizer_v80.zero_grad(set_to_none=True)
        final_grads = []
        for bg, rg in zip(base_grads, replay_grads):
            if bg is None and rg is None:
                final_grads.append(None)
                continue
            if bg is None:
                final_grads.append(replay_mix * rg)
                continue
            if rg is None:
                final_grads.append(bg)
                continue
            projected, conflicted, reduction = self.project_gradient_family_v78(
                bg, rg, strength=1.0, threshold=0.0
            )
            projection_ratio += float(reduction)
            final_grads.append(projected + float(replay_mix) * rg)
        for p, g in zip(active, final_grads):
            p.grad = g
        coverage = self._gradient_coverage_v80()
        grad_norm = float(nn.utils.clip_grad_norm_(active, self.model.cfg.unified_gradient_clip_v80).item())
        self.unified_optimizer_v80.step()
        self.unified_steps_v80 += 1
        denom = max(1, len(active))
        return {
            "loss": float(out["loss"].detach().item()),
            "memory_loss": float(out["memory_loss"].detach().item()),
            "predictive_loss": float(out["predictive_loss"].detach().item()),
            "world_loss": float(out["world_loss"].detach().item()),
            "spine_loss": float(out["spine_loss"].detach().item()),
            "cross_system_loss": float(out["cross_system_loss"].detach().item()),
            "temporal_loss": float(out["temporal_loss"].detach().item()),
            "replay_loss": float(replay_loss.detach().item()),
            "replay_available": replay_available,
            "replay_cosine": float(replay_cosine),
            "replay_mix": float(replay_mix),
            "replay_grad_norm": float(replay_grad_norm),
            "projection_ratio": float(projection_ratio / denom),
            "gradient_coverage": coverage["gradient_coverage"],
            "gradient_norm": grad_norm,
            "steps": float(self.unified_steps_v80),
        }

    def state_dict_v80(self) -> Dict[str, object]:
        return {
            "unified_optimizer": self.unified_optimizer_v80.state_dict(),
            "unified_steps": self.unified_steps_v80,
        }

    def load_state_dict_v80(self, state: Dict[str, object]) -> None:
        if state.get("unified_optimizer") is not None:
            self.unified_optimizer_v80.load_state_dict(state["unified_optimizer"])
        self.unified_steps_v80 = int(state.get("unified_steps", 0))


class OrganismRuntimeV80(OrganismRuntimeV79):
    """Runtime surface with a real, bounded use of the V80 learning spine.

    The historical runtime remains the primary planner. V80 adds a stateful recurrent
    context read that produces a small bounded action correction and is therefore a
    behavioral integration point, not diagnostics-only decoration.
    """

    def __init__(self, model: NeuroWeaveV80, trainer: Optional[OrganismTrainerV80] = None):
        super().__init__(model, trainer=trainer)
        self.v80_spine_state: Optional[Tensor] = None
        self.v80_memory_prior: Optional[Tensor] = None
        self.v80_runtime_steps = 0

    @staticmethod
    def _fit_dim(value: Tensor, dim: int) -> Tensor:
        value = value.reshape(value.size(0), -1)
        if value.size(-1) == dim:
            return value
        if value.size(-1) > dim:
            return value[..., :dim]
        return F.pad(value, (0, dim - value.size(-1)))

    def _runtime_features_v80(self, out: Dict[str, Tensor], observation: Tensor, goal: Optional[Tensor] = None) -> Tensor:
        ref = observation.reshape(1, -1)
        zero = lambda d: ref.new_zeros(1, d)
        previous_prior = self.v80_memory_prior if self.v80_memory_prior is not None else zero(self.model.cfg.action_dim)
        return torch.cat([
            self._fit_dim(out.get('brain_hidden_v46', zero(32)), 32),
            self._fit_dim(out.get('brain_current_latent_v47', zero(20)), 20),
            self._fit_dim(out.get('brain_workspace_v47', zero(24)), 24),
            self._fit_dim(out.get('brain_predicted_latent_v47', zero(20)), 20),
            self._fit_dim(out.get('world_next_v50', zero(20)), 20),
            self._fit_dim(out.get('brain_action_v47', out.get('chosen_action_v47', zero(3))), 3),
            self._fit_dim(previous_prior, 3),
            self._fit_dim(out.get('world_uncertainty', zero(1)), 1),
            self._fit_dim(out.get('brain_confidence_v47', zero(1)), 1),
            self._fit_dim(observation.reshape(1, -1), 9),
            self._fit_dim(goal.reshape(1, -1) if goal is not None else zero(8), 8),
        ], dim=-1)

    @torch.no_grad()
    def step(self, observation: Tensor, goal: Optional[Tensor] = None) -> Dict[str, Tensor]:
        out = super().step(observation, goal=goal)
        features = self._runtime_features_v80(out, observation, goal)
        spine = self.model.unified_spine_v80.step(features, self.v80_spine_state)
        self.v80_spine_state = spine['state'].detach()
        memory_read = self.model.neural_memory_v61(spine['memory_context'])['read']
        prior = 0.25 * torch.tanh(self.model.unified_spine_v80.memory_to_action(memory_read[..., :20]))
        self.v80_memory_prior = prior.detach()
        confidence = spine['confidence'].clamp(0.0, 1.0)
        correction = 0.10 * confidence * prior
        base_action = out.get('action', out.get('chosen_action_v47')).reshape(1, -1)
        action = (base_action + correction).clamp(-1.0, 1.0)
        self.v80_runtime_steps += 1
        out['action'] = action
        out['v80_spine_state'] = self.v80_spine_state
        out['v80_memory_read'] = memory_read
        out['v80_memory_prior'] = prior
        out['v80_spine_confidence'] = confidence
        out['v80_action_correction'] = correction
        out['v80_runtime_steps'] = observation.new_tensor([[float(self.v80_runtime_steps)]])
        report = self.model.learning_parameter_report_v80()
        out['v80_active_parameter_fraction'] = observation.new_tensor([[report['active_fraction']]])
        out['v80_unified_steps'] = observation.new_tensor([[float(getattr(self.trainer, 'unified_steps_v80', 0))]])
        return out

    def state_dict(self) -> Dict[str, object]:
        base = super().state_dict()
        base.update({
            'v80_spine_state': self.v80_spine_state.detach().cpu() if self.v80_spine_state is not None else None,
            'v80_memory_prior': self.v80_memory_prior.detach().cpu() if self.v80_memory_prior is not None else None,
            'v80_runtime_steps': self.v80_runtime_steps,
        })
        return base

    def load_state_dict(self, state: Dict[str, object]) -> None:
        super().load_state_dict(state)
        self.v80_spine_state = state.get('v80_spine_state')
        self.v80_memory_prior = state.get('v80_memory_prior')
        self.v80_runtime_steps = int(state.get('v80_runtime_steps', 0))


class RuntimeStateStoreV80(RuntimeStateStoreV79):
    VERSION = 80

    @classmethod
    def save(cls, path, model: NeuroWeaveV80, trainer: Optional[OrganismTrainerV80] = None, runtime: Optional[OrganismRuntimeV80] = None):
        torch.save({
            "version_v80": cls.VERSION,
            "base_version": 79,
            "model": model.state_dict(),
            "trainer": trainer.state_dict_v80() if trainer else None,
            "runtime": runtime.state_dict() if runtime else None,
        }, path)

    @classmethod
    def load(cls, path, model: NeuroWeaveV80, trainer: Optional[OrganismTrainerV80] = None, runtime: Optional[OrganismRuntimeV80] = None):
        payload = torch.load(path, map_location="cpu", weights_only=False)
        state = payload.get("model", payload)
        target = model.state_dict()
        compatible = {k: v for k, v in state.items() if k in target and tuple(v.shape) == tuple(target[k].shape)}
        missing = [k for k in target if k not in compatible]
        shape = [k for k in state if k in target and tuple(state[k].shape) != tuple(target[k].shape)]
        unexpected = [k for k in state if k not in target]
        model.load_state_dict(compatible, strict=False)
        optimizer_loaded = False
        optimizer_reset = False
        if trainer is not None and payload.get("trainer"):
            try:
                trainer.load_state_dict_v80(payload["trainer"])
                optimizer_loaded = True
            except (ValueError, RuntimeError):
                optimizer_reset = True
        if runtime is not None and payload.get("runtime") is not None:
            runtime.load_state_dict(payload["runtime"])
        return {
            "version": int(payload.get("version_v80", 0)),
            "loaded_tensors": len(compatible),
            "missing_tensors": missing,
            "shape_mismatch": shape,
            "unexpected_tensors": unexpected,
            "optimizer_loaded": optimizer_loaded,
            "optimizer_reset": optimizer_reset,
        }
