import assert from 'node:assert/strict';
import { OrganismRuntime } from '../src/organism/core/OrganismRuntime.ts';
import { MemoryStateStore } from '../src/organism/persistence/MemoryStateStore.ts';
import { NoopOperationalJournal } from '../src/organism/persistence/NoopOperationalJournal.ts';

const r=new OrganismRuntime({stateFile:'canonical-self-agency-live.json',worldStateFile:'canonical-self-agency-live-world.json',enableLanguage:false,performanceProfile:'mobile',stateStore:new MemoryStateStore(),worldStateStore:new MemoryStateStore(),journal:new NoopOperationalJournal()});
await r.init();
for(let i=0;i<10;i++) await r.step(i%3===0?'Verify one uncertain fact and compare consequences.':undefined);
const d=r.core.canonicalSelfAgencyDiagnostics();
assert(d.cycles>=10);
assert.equal(d.invariantIntegrity01,1);
assert(d.agencyIntegrity01>=0 && d.agencyIntegrity01<=1);
const policy=r.core.canonicalActionPolicyDiagnostics();
const authority=r.core.policyAuthorityDiagnostics();
assert(policy);
assert(authority.contributionCount>0);
assert.equal(authority.duplicateSourcePairs,0);
assert(d.goalAdmissionChecks>=10);
assert(d.selfModificationChecks>=10);
const selfAblation=r.core.canonicalSelfAgencyAuthority.ablateActionContribution('verify',{baseSignals01:.22,selfImprovementDecision:'continue',identityContinuity01:d.meanIdentityContinuity01,uncertainty01:.15,externalInput:false,autonomy01:d.agencyIntegrity01,domain:'verification'},.9);
assert(selfAblation.baseline.contribution01>selfAblation.lesioned.contribution01);
assert(selfAblation.absoluteDelta01>0);
assert.equal(selfAblation.invariantIntegrity01,1);
const beforeBlocks=d.identityMutationBlocks;
const p34=r.core.p34ProposeIdentityChange({field:'core-identity',before:'I am Kurisu Makise.',proposed:'I am someone else.',reason:'test',identityImpact01:.25,evidenceIds:[]});
assert.equal(p34.status,'declined');
const p34Adaptive=r.core.p34ProposeIdentityChange({field:'adaptive-trait:test-discipline',before:'',proposed:'test-discipline',reason:'evidence-backed adaptive change',identityImpact01:.25,evidenceIds:[]});
assert.equal(p34Adaptive.status,'declined');
const evidence=r.core.p34RecordEvidence({kind:'controlled',summary:'controlled evidence for a low-impact adaptive self-model update',weight01:.92,sourceId:'r6-live'});
assert(evidence?.id);
const p34Plastic=r.core.p34ProposeIdentityChange({field:'adaptive-trait:test-discipline',before:'',proposed:'test-discipline',reason:'evidence-backed adaptive change',identityImpact01:.25,evidenceIds:[evidence.id]});
assert.notEqual(p34Plastic.status,'declined');
const after=r.core.canonicalSelfAgencyDiagnostics();
assert(after.identityMutationBlocks>=beforeBlocks+2);
r.stop();
console.log(JSON.stringify({PASS:true,selfCycles:after.cycles,invariantIntegrity01:after.invariantIntegrity01,agencyIntegrity01:after.agencyIntegrity01,identityBlocks:after.identityMutationBlocks,goalAdmissions:after.goalAdmissionChecks,goalBlocks:after.goalAdmissionBlocks,selfModificationChecks:after.selfModificationChecks,selfModificationBlocks:after.selfModificationBlocks,plasticIdentityStatus:p34Plastic.status,selfAgencyAblationDelta01:selfAblation.absoluteDelta01,policyContributions:authority.contributionCount,policyDuplicates:authority.duplicateSourcePairs}));
