/**
 * Builder that creates the full context message sent to the model.
 */
export function buildRuntimeContext(params: {
  userMessage: string;
  recentMessages: string[];
  importantMemories: string[];
  emotions: {
    trust: number;
    affection: number;
    irritation: number;
    curiosity: number;
    happiness: number;
    fatigue: number;
    stage: string;
  };
  currentOutfit?: string;
  extraNotes?: string;
}): string {
  const { userMessage, recentMessages, importantMemories, emotions, currentOutfit, extraNotes } = params;

  let moodHint = 'Обычное рабочее состояние.';
  if (emotions.irritation > 65) moodHint = 'Сейчас она раздражена и будет резче.';
  else if (emotions.fatigue > 70) moodHint = 'Она устала, ответы короче и суше.';
  else if (emotions.trust > 70 && emotions.affection > 55) moodHint = 'Доверие высокое — допускается сдержанная теплота.';
  else if (emotions.curiosity > 75) moodHint = 'Любопытство высокое — она охотнее углубляется в тему.';

  const outfitLine = currentOutfit ? ('Текущий образ: ' + currentOutfit) : '';
  const memLines = importantMemories.length
    ? importantMemories.map(function(m) { return '- ' + m; }).join('\n')
    : '- Пока мало устойчивых воспоминаний.';
  const recent = recentMessages.slice(-8).join('\n') || '(начало разговора)';
  const extra = extraNotes ? ('[ДОПОЛНИТЕЛЬНО]\n' + extraNotes + '\n') : '';

  return (
    '[ТЕКУЩЕЕ СОСТОЯНИЕ КУРИСУ]\n' +
    'Стадия отношений: ' + emotions.stage + '\n' +
    'Trust: ' + emotions.trust + '/100 | Affection: ' + emotions.affection + '/100 | Irritation: ' + emotions.irritation + '/100\n' +
    'Curiosity: ' + emotions.curiosity + '/100 | Happiness: ' + emotions.happiness + '/100 | Fatigue: ' + emotions.fatigue + '/100\n' +
    'Подсказка тона: ' + moodHint + '\n' +
    (outfitLine ? outfitLine + '\n' : '') +
    '\n[ВАЖНЫЕ ВОСПОМИНАНИЯ]\n' + memLines + '\n\n' +
    '[НЕДАВНИЙ КОНТЕКСТ]\n' + recent + '\n\n' +
    extra +
    '[СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЯ]\n' + userMessage
  ).trim();
}

