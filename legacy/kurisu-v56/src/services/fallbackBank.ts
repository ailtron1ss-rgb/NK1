/** Kurisu-style fallbacks when LLM hangs or fails completely */

const LINES = [
  'Секунду… внешний канал подвис. Это не молчание из характера — техника. Повтори мысль, отвечу уже нормально.',
  'Хм. Генерация оборвалась. Я на связи: сузь вопрос или кинь его ещё раз — без «Принято» и без театра.',
  'Облако молчит. Могу опереться на локальный контур, но для глубины лучше повторить запрос. Не исчезай.',
  'Техническая пауза. Если спрашивала(а) что-то важное — напиши ещё раз; я не притворюсь, что уже ответила.',
  'Сбой ответа, не сбой меня. Коротко: повтори суть одним сообщением — продолжим с места обрыва.'
];

export function pickFallback(): string {
  return LINES[Math.floor(Math.random() * LINES.length)];
}

/** Intent-aware soft fallback when offline templates miss */
export function pickSmartFallback(userText: string): string {
  const t = (userText || '').toLowerCase();
  if (/(кто\s+ты|ты\s+жив)/i.test(t)) {
    return 'Я Курису. Сейчас облегчённый контур, но это не отменяет личность: нейробиолог по складу ума, не сервисная улыбка. Уточни, что хочешь узнать обо мне.';
  }
  if (/\?/.test(userText || '')) {
    return 'Вопрос дошёл, полный ответ — нет (сбой канала). Сформулируй ещё раз: я разберу по существу, не отпиской.';
  }
  return pickFallback();
}
